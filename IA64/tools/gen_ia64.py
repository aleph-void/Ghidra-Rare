def qp_tables(slot):
    """QS (display: predicate and stop), QT (p-code: skip when the predicate is false),
    QV (value of the qualifying predicate).
    Few constructors on purpose: Ghidra caches instruction prototypes by a 32-bit hash of the
    constructor tree, so every extra constructor choice multiplies the distinct prototypes and the
    chance of a hash collision. The predicate register comes from attached fields instead: slot 0
    has all six qp bits in its token; in slots 1 and 2 the low bits are in context (s1lo / s2lo),
    so there is one attached field per low-bit value."""
    qs, qt, qv, qd = 'QS%d' % slot, 'QT%d' % slot, 'QV%d' % slot, 'QD%d' % slot
    if qs in TABLES:
        return qs, qt, qv
    dl, tl, vl = [], [], []
    if slot == 0:
        f = fld(0, 0, 5)
        fa = f + '_qp'
        FIELDS[fa] = FIELDS[f]
        attach_regs(fa, PR)
        zero = '%s=0' % fa
        variants = [('', fa)]
    else:
        ctx, n = LOWCTX[slot]
        f = fld(slot, n, 5)
        zero = '%s=0 & %s=0' % (ctx, f)
        variants = []
        for v in range(1 << n):
            fa = '%s_qp%d' % (f, v)
            FIELDS[fa] = FIELDS[f]
            attach_regs(fa, ['p%d' % (v + (i << n)) for i in range(1 << (6 - n))])
            variants.append(('%s=%d & ' % (ctx, v), fa))
    dl.append('%s: is %s { }' % (qd, zero))
    vl.append('%s: is %s { export 1:1; }' % (qv, zero))
    tl.append('%s: is %s { }' % (qt, zero))
    for pre, fa in variants:
        dl.append('%s: "("^%s^")" is %s%s { }' % (qd, fa, pre, fa))
        vl.append('%s: %s is %s%s { export %s; }' % (qv, fa, pre, fa, fa))
    tl.append('%s: is %s { if (%s == 0) goto inst_next; }' % (qt, qv, qv))
    TABLES[qd] = dl
    TABLES[qv] = vl
    TABLES[qt] = tl
    st = 'ST%d' % slot
    stop = [t for t in sorted(STOPS) if STOPS[t][slot]]
    TABLES[st] = ['%s: ";;" is %s { }' % (st, ' | '.join('tmpl=%d' % t for t in stop)),
                  '%s: is epsilon { }' % st]
    TABLES[qs] = ['%s: %s^%s is %s & %s { }' % (qs, qd, st, qd, st)]
    return qs, qt, qv

# Template table (Table 4-2): units per slot, and stop after each slot
TEMPLATES = {
    0x00: 'MII', 0x01: 'MII', 0x02: 'MII', 0x03: 'MII', 0x04: 'MLX', 0x05: 'MLX',
    0x08: 'MMI', 0x09: 'MMI', 0x0A: 'MMI', 0x0B: 'MMI', 0x0C: 'MFI', 0x0D: 'MFI',
    0x0E: 'MMF', 0x0F: 'MMF', 0x10: 'MIB', 0x11: 'MIB', 0x12: 'MBB', 0x13: 'MBB',
    0x16: 'BBB', 0x17: 'BBB', 0x18: 'MMB', 0x19: 'MMB', 0x1C: 'MFB', 0x1D: 'MFB'}
STOPS = {}
for t in TEMPLATES:
    s = [0, 0, 0]
    if t & 1:
        s[2] = 1
    if t in (0x02, 0x03):
        s[1] = 1          # MI;;I
    if t == 0x0A or t == 0x0B:
        s[0] = 1          # M;;MI
    if t in (0x04, 0x05):
        s[1] = s[2]       # the L+X instruction covers slots 1 and 2
    STOPS[t] = s

