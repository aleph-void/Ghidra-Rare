LD_VARIANTS = {0: '', 1: '.s', 2: '.a', 3: '.sa', 4: '.bias', 5: '.acq', 8: '.c.clr', 9: '.c.nc',
               0xA: '.c.clr.acq'}
FPLD_VARIANTS = {0: '', 1: '.s', 2: '.a', 3: '.sa', 8: '.c.clr', 9: '.c.nc'}
FPSZ = {0: ('e', 10), 1: ('8', 8), 2: ('s', 4), 3: ('d', 8)}

def fp_load_sem(code, dst, sig, exp, addr):
    """p-code loading FP memory format 'code' at addr into dst (10-byte) / sig / exp"""
    if code == 's':
        return '%s = float2float(*:4 %s);' % (dst, addr)
    if code == 'd':
        return '%s = float2float(*:8 %s);' % (dst, addr)
    if code == '8':
        return '%s = *:8 %s; %s = 0x103e;' % (sig, addr, exp) if False else '%s = *:8 %s; %s = 0x403e;' % (sig, addr, exp)
    if code == 'e':
        return '%s = *:10 %s;' % (dst, addr)
    if code == 'fill':
        return '%s = *:8 %s; %s = *:2 (%s + 8);' % (sig, addr, exp, addr)
    raise ValueError(code)

def fp_store_sem(code, src, sig, exp, addr):
    if code == 's':
        return '*:4 %s = float2float(%s);' % (addr, src)
    if code == 'd':
        return '*:8 %s = float2float(%s);' % (addr, src)
    if code == '8':
        return '*:8 %s = %s;' % (addr, sig)
    if code == 'e':
        return '*:10 %s = %s;' % (addr, src)
    if code == 'spill':
        return '*:8 %s = %s; *:8 (%s + 8) = zext(%s);' % (addr, sig, addr, exp)
    raise ValueError(code)

def gen_M(k, tab):
    R = regs3(k)
    r3d = grd(k, 20, 26)
    ldh, sth, lfh = LDH(k), STH(k), LFH(k)
