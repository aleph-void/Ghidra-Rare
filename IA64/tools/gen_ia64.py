def bundle_next():
    return '(inst_start - (inst_start & 15) + 16)'

RSE_CALL = (
    # Both models first save the caller's locals r32..r32+sol-1 in argsave0.. and move its
    # outputs r32+sol.. down to r32.. (ARGS; sol and the output count come from the alloc
    # context). Doing this unconditionally keeps values such as a gp saved in a local register
    # constant across the call even before the decompiler has folded the DECOMPILE_MODE test
    # (switch recovery runs on such partial functions).
    # Emulation (DECOMPILE_MODE = 0) then spills the saved locals to the backing store at ar.bsp
    # (RSPILL). The p-code after the call op only runs in the decompiler's model: there, the
    # outputs and the caller's locals come back from argsave (ARGR / ARGL).
    'build ARGS; if (DECOMPILE_MODE) goto <docall>; build RSPILL; <docall> ')

# br.ret in emulation: restore the caller's locals (sol from ar.pfs) from the backing store.
# Unrolled with static register names, so the decompiler sees no register-space stores.
RSE_RET = (
    'local pfm:8 = ar.pfs & 0x3fffffffff; if (DECOMPILE_MODE) goto <rdone>;'
    ' local sc:8 = (pfm >> 7) & 0x7f; ar.bsp = ar.bsp - sc * 8;' +
    ''.join(' if (sc %s) goto <rdone>; r%d = *:8 (ar.bsp + %d);' % ('== 0' if i == 0 else '<= %d' % i, 32 + i, 8 * i)
            for i in range(96)) +
    ' <rdone> cfm = pfm; ar.ec = (ar.pfs >> 52) & 0x3f; ')

def frame_tables():
    TABLES.setdefault('FSOL', ['FSOL: val is cfm_sol [ val = cfm_sol + 0; ] { export *[const]:8 val; }'])
    TABLES.setdefault('FOUT', ['FOUT: val is cfm_out [ val = cfm_out + 0; ] { export *[const]:8 val; }'])
    return 'FSOL', 'FOUT'

def NB(k):
    return table('NB', ['NB: val is epsilon [ val = inst_start - (inst_start & 15) + 16; ] { export *:8 val; }'])

def rot_tables():
    """ROTATE: register rotation of rotate_regs() by one position (rrb decremented): GRs
    r32..r32+8*sor-1 with their NaT bits (sor from the frame context), f32-f127, p16-p63."""
    name = 'ROTATE'
    if name in TABLES:
        return name
    lines = []
    fr = ' local tf:10 = f127;' + ''.join(' f%d = f%d;' % (i, i - 1) for i in range(127, 32, -1)) + ' f32 = tf;'
    pr = ' local tp:1 = p63;' + ''.join(' p%d = p%d;' % (i, i - 1) for i in range(63, 16, -1)) + ' p16 = tp;'
    for sor in range(16):
        n = min(sor * 8, 96)
        gr = ''
        if n:
            last = 32 + n - 1
            gr = ' local tg:8 = r%d; local tn:1 = r%d.nat;' % (last, last)
            gr += ''.join(' r%d = r%d; r%d.nat = r%d.nat;' % (i, i - 1, i, i - 1) for i in range(last, 32, -1))
            gr += ' r32 = tg; r32.nat = tn;'
        lines.append('%s: is cfm_sor=%d {%s%s%s }' % (name, sor, gr, fr, pr))
    TABLES[name] = lines
    return name

def arg_tables():
    """ARGS / ARGR: the register stack at br.call. The caller's output registers
    r32+sol .. r32+sol+n-1 (sol and n = min(outputs, 8) from the alloc context) become the
    callee's r32.., and the caller's r32.. are restored after the call."""
    if 'ARGS' in TABLES:
        return 'ARGS', 'ARGR'
    for j in range(8):
        nm = 'OUT%d' % j
        TABLES[nm] = ['%s: is cfm_sol=%d { export r%d; }' % (nm, s, min(32 + s + j, 127)) for s in range(128)]
    a, sp = [], []
    for v in range(128):
        n = min(v, 8)
        outs = ''.join(' & OUT%d' % j for j in range(n))
        body = ' build ARGSV;'
        body += ''.join(' r%d = OUT%d;' % (32 + j, j) for j in range(n))
        a.append('ARGS: is cfm_out=%d%s & ARGSV { %s }' % (v, outs, body))
        # OUTj = r32+sol+j is never below r32+j, so copying in increasing j is safe
        sp.append('RSPILL: is cfm_sol=%d { %s ar.bsp = ar.bsp + %d; }' % (
            v, ''.join(' *:8 (ar.bsp + %d) = argsave%d;' % (8 * i, i) for i in range(min(v, 96))), 8 * min(v, 96)))
    # After the call: the outputs hold what the callee left in its r32.. (they are dead to the
    # caller), then the caller's locals among r32..r39 are restored (ARGL, keyed on sol).
    r = []
    for v in range(128):
        n = min(v, 8)
        outs = ''.join(' & OUT%d' % j for j in range(n))
        r.append('ARGR: is cfm_out=%d%s & ARGL { %s build ARGL; }' % (v, outs, ''.join(' OUT%d = r%d;' % (j, 32 + j)
                                                                               for j in range(n))))
    # the caller's locals r32..r32+sol-1 (the whole local frame) are saved before the call and
    # restored after it, so the stacked registers need not be "unaffected" in the cspec
    TABLES['ARGSV'] = ['ARGSV: is cfm_sol=%d { %s }' % (v, ''.join(' argsave%d = r%d;' % (j, 32 + j)
                                                                for j in range(min(v, 96)))) for v in range(128)]
    TABLES['ARGL'] = ['ARGL: is cfm_sol=%d { %s }' % (v, ''.join(' r%d = argsave%d;' % (32 + j, j)
                                                              for j in range(min(v, 96)))) for v in range(128)]
    TABLES['RSPILL'] = sp
    TABLES['ARGS'] = a
    TABLES['ARGR'] = r
    return 'ARGS', 'ARGR'

def gen_B(k, tab):
    bwh, ph, dh = BWH(k), PH(k), DH(k)
    qs, qt, qv = qp_tables(k)
    tgt = TGT25(k)
    nxt = bundle_next()
    rot = rot_tables()
    args, argr = arg_tables()
    # 'br' pseudo-op: qp = 0 and .sptk
    BRC = 'BRC%d' % k
    table(BRC, ['%s: "br" is %s & %s=0 { }' % (BRC, ' & '.join(C(k, (0, 5, 0))), fld(k, 33, 34)),
                '%s: "br.cond"^%s is %s { }' % (BRC, bwh, bwh)])
    base = lambda op, bt: C(k, (37, 40, op), (6, 8, bt))
    ops = dict(t=tgt, w=bwh, p=ph, d=dh, c=BRC)
    emit_ins(tab, k, '{c}{p}{d}', '{t}', base(4, 0), ops, 'goto {t};')
    # br.call b1=target25: b1 = return link (next bundle), ar.pfs = frame marker, outputs -> r32..
    b1 = brr(k, 6, 8)
    callsem = ('{b1} = %s; ar.pfs = (ar.ec << 52) | cfm; %s call {t}; build ARGR; %s' %
               (nxt, RSE_CALL, '' if k == 2 else 'goto {nb};'))
    emit_ins(tab, k, 'br.call{w}{p}{d}', '{b1}={t}', C(k, (37, 40, 5)), dict(ops, b1=b1, nb=NB(k)), callsem,
             extra_syms=(args, argr, 'RSPILL'))
    # counted / modulo-scheduled loops (slot 2 only; qp is 0 for B2)
    emit_ins(tab, k, 'br.cloop{w}{p}{d}', '{t}', base(4, 5), ops,
             'if (ar.lc == 0) goto inst_next; ar.lc = ar.lc - 1; goto {t};', qp='stop')
    ctop = ('local lc:1 = ar.lc != 0; local ecz:1 = ar.ec != 0; local tk:1 = lc || (ar.ec > 1);'
            ' if (!lc && !ecz) goto <norot>;'
            ' ar.lc = ar.lc - zext(lc); ar.ec = ar.ec - zext(!lc); p63 = lc; build ROTATE; goto <done>;'
            ' <norot> p63 = 0; <done>')
    emit_ins(tab, k, 'br.ctop{w}{p}{d}', '{t}', base(4, 7), ops,
             ctop + ' if (tk) goto {t};', qp='stop', extra_syms=(rot,))
    emit_ins(tab, k, 'br.cexit{w}{p}{d}', '{t}', base(4, 6), ops,
             ctop + ' if (!tk) goto {t};', qp='stop', extra_syms=(rot,))
    wtop = ('local q:1 = {qv}; local ecz:1 = ar.ec != 0; local tk:1 = q || (ar.ec > 1); p63 = 0;'
            ' if (!q && !ecz) goto <done>; ar.ec = ar.ec - zext(!q); build ROTATE; <done>')
    emit_ins(tab, k, 'br.wtop{w}{p}{d}', '{t}', base(4, 3), ops, wtop + ' if (tk) goto {t};', qp='none',
             extra_syms=(rot,))
    emit_ins(tab, k, 'br.wexit{w}{p}{d}', '{t}', base(4, 2), ops, wtop + ' if (!tk) goto {t};', qp='none',
             extra_syms=(rot,))
    # indirect
    b2 = brr(k, 13, 15)
    ops = dict(b2=b2, w=bwh, p=ph, d=dh, c=BRC, b1=b1)
    ind = lambda x6, bt: C(k, (37, 40, 0), (27, 32, x6), (6, 8, bt))
    emit_ins(tab, k, '{c}{p}{d}', '{b2}', ind(0x20, 0), ops, 'goto [{b2}];')
    emit_ins(tab, k, 'br.ia{w}{p}{d}', '{b2}', ind(0x20, 1), ops, 'ia64_br_ia({b2}); goto [{b2}];')
    emit_ins(tab, k, 'br.ret{w}{p}{d}', '{b2}', ind(0x21, 4), ops,
             RSE_RET + 'return [{b2}];')
    bwh3 = BWH3(k)
    callsem = ('local dst:8 = {b2}; {b1} = %s; ar.pfs = (ar.ec << 52) | cfm; %s call [dst]; build ARGR; %s'
               % (nxt, RSE_CALL, '' if k == 2 else 'goto {nb};'))
    emit_ins(tab, k, 'br.call{x}{p}{d}', '{b1}={b2}', C(k, (37, 40, 1)) + C(k, (32, 32, 1)), dict(ops, x=bwh3, nb=NB(k)),
             callsem, extra_syms=(args, argr, 'RSPILL'))
    # misc (B8): bits 0-5 are 0
    for x6, mn, sem in ((2, 'cover', 'ia64_cover();'), (4, 'clrrrb', 'ia64_clrrrb();'),
                        (5, 'clrrrb.pr', 'ia64_clrrrb_pr();'), (8, 'rfi', 'return [cr.iip];'),
                        (0xC, 'bsw.0', 'ia64_bsw0();'), (0xD, 'bsw.1', 'ia64_bsw1();'), (0x10, 'epc', 'ia64_epc();'),
                        (0x18, 'vmsw.0', 'ia64_vmsw0();'), (0x19, 'vmsw.1', 'ia64_vmsw1();')):
        emit_ins(tab, k, mn, '', C(k, (37, 40, 0), (27, 32, x6)), {}, sem, qp='stop')
    i21 = IMM21(k)
    emit_break(tab, k, 'break.b', C(k, (37, 40, 0), (27, 32, 0)), dict(i=i21))
    emit_ins(tab, k, 'nop.b', '{i}', C(k, (37, 40, 2), (27, 32, 0)), dict(i=i21), '')
    emit_ins(tab, k, 'hint.b', '{i}', C(k, (37, 40, 2), (27, 32, 1)), dict(i=i21), 'ia64_hint({i});')
    # branch predict (no qp: bits 0-5 hold wh / ignored bits)
    ih, indwh, ipwh = IH35(k), INDWH(k), IPWH(k)
    ops = dict(b2=b2, t=TAG13A(k), ih=ih, w=indwh)
    emit_ins(tab, k, 'brp{w}{ih}', '{b2},{t}', C(k, (37, 40, 2), (27, 32, 0x10)), ops, '', qp='stop')
    emit_ins(tab, k, 'brp.ret{w}{ih}', '{b2},{t}', C(k, (37, 40, 2), (27, 32, 0x11)), ops, '', qp='stop')
    ops = dict(t=tgt, g=TAG13A(k), ih=ih, w=ipwh)
    emit_ins(tab, k, 'brp{w}{ih}', '{t},{g}', C(k, (37, 40, 7)), ops, '', qp='stop')

# =============================================================================================
# F-unit (Section 4.6). FRs are 80-bit double-extended values: fN (10 bytes), fNs (significand),
# fNe (sign and 15-bit exponent). The integer exponent 0x1003E of the 82-bit register format
# is 0x403E here.
# =============================================================================================
def fsigs(k, lo, hi):
    """significand of an FR source (f0 = 0, f1 = 0x8000000000000000)"""
    f = frsig(k, lo, hi)
    name = 'FSG%d_%d_%d' % (k, lo, hi)
    return table(name, ['%s: is %s=0 { export 0:8; }' % (name, f),
                        '%s: is %s=1 { export 0x8000000000000000:8; }' % (name, f),
                        '%s: is %s { export %s; }' % (name, f, f)])

def fexps(k, lo, hi):
    f = frexp(k, lo, hi)
    name = 'FEX%d_%d_%d' % (k, lo, hi)
    return table(name, ['%s: is %s=0 { export 0:2; }' % (name, f),
                        '%s: is %s=1 { export 0x3fff:2; }' % (name, f),
                        '%s: is %s { export %s; }' % (name, f, f)])

def fregs(k):
    d = dict(f1=frd(k, 6, 12), f1s=frsig(k, 6, 12), f1e=frexp(k, 6, 12))
    for n, (lo, hi) in (('2', (13, 19)), ('3', (20, 26)), ('4', (27, 33))):
        d['f' + n] = frs(k, lo, hi)
        d['f%ss' % n] = fsigs(k, lo, hi)
        d['f%se' % n] = fexps(k, lo, hi)
    return d

INTRES = '{f1e} = 0x403e;'

def par2(fn):
    """parallel single-precision: fn(lo_or_hi) -> statements leaving 4-byte local x<lane>"""
    s = fn(0) + ' ' + fn(1)
    return s + ' {f1s} = (zext(fx1) << 32) | zext(fx0); ' + INTRES

def gen_F(k, tab):
    F = fregs(k)
    sf = SF(k)
    F['sf'] = sf
    def f0(x6, x=0):
        return C(k, (37, 40, 0), (33, 33, x), (27, 32, x6))
    def f1o(x6, x=0):
        return C(k, (37, 40, 1), (33, 33, x), (27, 32, x6))
    i21 = IMM21(k)
    emit_break(tab, k, 'break.f', f0(0), dict(i=i21))
    emit_ins(tab, k, 'nop.f', '{i}', f0(1) + C(k, (26, 26, 0)), dict(i=i21), '')
    emit_ins(tab, k, 'hint.f', '{i}', f0(1) + C(k, (26, 26, 1)), dict(i=i21), 'ia64_hint({i});')
    am, om = imm(k, 'AMASK7', [(13, 19, False)], '$0'), imm(k, 'OMASK7', [(20, 26, False)], '$0')
    sfv = imm(k, 'SFV', [(34, 35, False)], '$0')
    emit_ins(tab, k, 'fsetc{sf}', '{a},{o}', f0(4), dict(F, a=am, o=om, v=sfv),
             'local sh:8 = 6 + 13 * {v}; local c:8 = (((ar.fpsr >> 6) & 0x7f) & {a}) | {o};'
             ' ar.fpsr = (ar.fpsr & ~(0x7f << sh)) | (c << sh);')
    emit_ins(tab, k, 'fclrf{sf}', '', f0(5), dict(F, v=sfv),
             'local sh:8 = 13 + 13 * {v}; ar.fpsr = ar.fpsr & ~(0x3f << sh);')
    emit_ins(tab, k, 'fchkf{sf}', '{t}', f0(8), dict(F, t=TGT25F(k)), 'local m:1 = ia64_fchkf(); if (m) goto {t};')
    emit_ins(tab, k, 'fmerge.s', '{f1}={f2},{f3}', f0(0x10), F,
             '{f1e} = ({f2e} & 0x8000) | ({f3e} & 0x7fff); {f1s} = {f3s};')
    emit_ins(tab, k, 'fmerge.ns', '{f1}={f2},{f3}', f0(0x11), F,
             '{f1e} = (~{f2e} & 0x8000) | ({f3e} & 0x7fff); {f1s} = {f3s};')
    # pseudo-ops (instruction pages of fmerge, fabs, fneg, fnegabs, mov): f2 = f3 before f2 = f0
    emit_ins(tab, k, 'fabs', '{f1}={f3}', f0(0x10) + C(k, (13, 19, 0)), F, '{f1e} = {f3e} & 0x7fff; {f1s} = {f3s};')
    emit_ins(tab, k, 'fnegabs', '{f1}={f3}', f0(0x11) + C(k, (13, 19, 0)), F, '{f1e} = {f3e} | 0x8000; {f1s} = {f3s};')
    emit_ins(tab, k, 'fpabs', '{f1}={f3}', f1o(0x10) + C(k, (13, 19, 0)), F,
             '{f1s} = {f3s} & 0x7fffffff7fffffff; ' + INTRES)
    emit_ins(tab, k, 'fpnegabs', '{f1}={f3}', f1o(0x11) + C(k, (13, 19, 0)), F,
             '{f1s} = {f3s} | 0x8000000080000000; ' + INTRES)
    for i in range(128):
        same = C(k, (13, 19, i), (20, 26, i))
        emit_ins(tab, k, 'mov', '{f1}={f3}', f0(0x10) + same, F, '{f1} = {f3};')
        emit_ins(tab, k, 'fneg', '{f1}={f3}', f0(0x11) + same, F, '{f1e} = {f3e} ^ 0x8000; {f1s} = {f3s};')
        emit_ins(tab, k, 'fpneg', '{f1}={f3}', f1o(0x11) + same, F,
                 '{f1s} = {f3s} ^ 0x8000000080000000; ' + INTRES)
    emit_ins(tab, k, 'fmerge.se', '{f1}={f2},{f3}', f0(0x12), F, '{f1e} = {f2e}; {f1s} = {f3s};')
    minmax = {0x14: ('fmin', 'A f< B', False), 0x15: ('fmax', 'B f< A', False),
              0x16: ('famin', 'abs(A) f< abs(B)', True), 0x17: ('famax', 'abs(B) f< abs(A)', True)}
    for x6, (mn, cond, _) in minmax.items():
        emit_ins(tab, k, mn + '{sf}', '{f1}={f2},{f3}', f0(x6), F,
                 'local fa:10 = {f2}; local fb:10 = {f3}; {f1} = fb; if (!(%s)) goto <e>; {f1} = fa; <e>' % cond.replace('A', 'fa').replace('B', 'fb'))
        def lane(i, cond=cond):
            return ('local fa%d:4 = ({f2s} >> %d):4; local fb%d:4 = ({f3s} >> %d):4; local fx%d:4 = fb%d;'
                    ' if (!(%s)) goto <s%d>; fx%d = fa%d; <s%d>' %
                    (i, 32 * i, i, 32 * i, i, i, cond.replace('A', 'fa%d' % i).replace('B', 'fb%d' % i),
                     i, i, i, i))
        emit_ins(tab, k, 'fp' + mn[1:] + '{sf}', '{f1}={f2},{f3}', f1o(x6), F, par2(lane))
    cvt = {0x18: ('fcvt.fx', 'trunc(round(A))'), 0x19: ('fcvt.fxu', 'trunc(round(A))'),
           0x1A: ('fcvt.fx.trunc', 'trunc(A)'), 0x1B: ('fcvt.fxu.trunc', 'trunc(A)')}
    for x6, (mn, e) in cvt.items():
        emit_ins(tab, k, mn + '{sf}', '{f1}={f2}', f0(x6), F,
                 'local fa:10 = {f2}; local v:8 = %s; {f1s} = v; %s' % (e.replace('A', 'fa'), INTRES))
        emit_ins(tab, k, 'fp' + mn[1:] + '{sf}', '{f1}={f2}', f1o(x6), F, par2(
            lambda i, e=e: 'local fa%d:4 = ({f2s} >> %d):4; local fx%d:4 = %s;' % (i, 32 * i, i, e.replace('A', 'fa%d' % i))))
    emit_ins(tab, k, 'fcvt.xf', '{f1}={f2}', f0(0x1C), F, 'local v:8 = {f2s}; {f1} = int2float(v);')
    emit_ins(tab, k, 'fpack', '{f1}={f2},{f3}', f0(0x28), F,
             'local hi:4 = float2float({f2}); local lo:4 = float2float({f3}); {f1s} = (zext(hi) << 32) | zext(lo); '
             + INTRES)
    for x6, mn, op in ((0x2C, 'fand', '{f2s} & {f3s}'), (0x2D, 'fandcm', '{f2s} & ~{f3s}'),
                       (0x2E, 'for', '{f2s} | {f3s}'), (0x2F, 'fxor', '{f2s} ^ {f3s}')):
        emit_ins(tab, k, mn, '{f1}={f2},{f3}', f0(x6), F, '{f1s} = %s; %s' % (op, INTRES))
    hi = lambda f: '(%s >> 32)' % f
    lo = lambda f: '(%s & 0xffffffff)' % f
    pairs = {0x34: ('fswap', lo('{f3s}'), hi('{f2s}')),
             0x35: ('fswap.nl', '(%s ^ 0x80000000)' % lo('{f3s}'), hi('{f2s}')),
             0x36: ('fswap.nr', lo('{f3s}'), '(%s ^ 0x80000000)' % hi('{f2s}')),
             0x39: ('fmix.lr', hi('{f2s}'), lo('{f3s}')),
             0x3A: ('fmix.r', lo('{f2s}'), lo('{f3s}')),
             0x3B: ('fmix.l', hi('{f2s}'), hi('{f3s}')),
             0x3C: ('fsxt.r', '(0 - (({f2s} >> 31) & 1)) & 0xffffffff', lo('{f3s}')),
             0x3D: ('fsxt.l', '(0 - (({f2s} >> 63) & 1)) & 0xffffffff', hi('{f3s}'))}
    for x6, (mn, h, l) in pairs.items():
        emit_ins(tab, k, mn, '{f1}={f2},{f3}', f0(x6), F, '{f1s} = (%s << 32) | %s; %s' % (h, l, INTRES))
    for x6, mn, sgn in ((0x10, 'fpmerge.s', 's'), (0x11, 'fpmerge.ns', 'ns'), (0x12, 'fpmerge.se', 'se')):
        if sgn == 's':
            m = '(({f2s} & 0x8000000080000000) | ({f3s} & 0x7fffffff7fffffff))'
        elif sgn == 'ns':
            m = '((~{f2s} & 0x8000000080000000) | ({f3s} & 0x7fffffff7fffffff))'
        else:
            m = '(({f2s} & 0xff800000ff800000) | ({f3s} & 0x007fffff007fffff))'
        emit_ins(tab, k, mn, '{f1}={f2},{f3}', f1o(x6), F, '{f1s} = %s; %s' % (m, INTRES))
    rels = {0x30: 'eq', 0x31: 'lt', 0x32: 'le', 0x33: 'unord', 0x34: 'neq', 0x35: 'nlt', 0x36: 'nle', 0x37: 'ord'}
    fr = {'eq': 'A f== B', 'lt': 'A f< B', 'le': 'A f<= B', 'unord': 'nan(A) || nan(B)',
          'neq': '!(A f== B)', 'nlt': '!(A f< B)', 'nle': '!(A f<= B)', 'ord': '!(nan(A) || nan(B))'}
    for x6, rel in rels.items():
        emit_ins(tab, k, 'fpcmp.%s{sf}' % rel, '{f1}={f2},{f3}', f1o(x6), F, par2(
            lambda i, rel=rel: 'local fa%d:4 = ({f2s} >> %d):4; local fb%d:4 = ({f3s} >> %d):4; local fx%d:4 = 0 - zext(%s);'
            % (i, 32 * i, i, 32 * i, i, fr[rel].replace('A', 'fa%d' % i).replace('B', 'fb%d' % i))))
    # reciprocal approximations (x = 1): exact reciprocals; p2 = 1 (refinement needed)
    P2 = dict(F, p2=prd(k, 27, 32))
    emit_ins(tab, k, 'frcpa{sf}', '{f1},{p2}={f2},{f3}', C(k, (37, 40, 0), (33, 33, 1), (36, 36, 0)), P2,
             'local one:10 = int2float(1:8); {f1} = one f/ {f3}; {p2} = 1;')
    emit_ins(tab, k, 'frsqrta{sf}', '{f1},{p2}={f3}', C(k, (37, 40, 0), (33, 33, 1), (36, 36, 1)), P2,
             'local one:10 = int2float(1:8); {f1} = one f/ sqrt({f3}); {p2} = 1;')
    emit_ins(tab, k, 'fprcpa{sf}', '{f1},{p2}={f2},{f3}', C(k, (37, 40, 1), (33, 33, 1), (36, 36, 0)), P2, par2(
        lambda i: 'local fb%d:4 = ({f3s} >> %d):4; local fo%d:4 = int2float(1:4); local fx%d:4 = fo%d f/ fb%d;'
        % (i, 32 * i, i, i, i, i)) + ' {p2} = 1;')
    emit_ins(tab, k, 'fprsqrta{sf}', '{f1},{p2}={f3}', C(k, (37, 40, 1), (33, 33, 1), (36, 36, 1)), P2, par2(
        lambda i: 'local fb%d:4 = ({f3s} >> %d):4; local fo%d:4 = int2float(1:4); local fx%d:4 = fo%d f/ sqrt(fb%d);'
        % (i, 32 * i, i, i, i, i)) + ' {p2} = 1;')
    # fcmp (op 4)
    P = dict(F, p1=prd(k, 6, 11), p2=prd(k, 27, 32))
    for ra, rb, rel, cond in ((0, 0, 'eq', '{f2} f== {f3}'), (0, 1, 'lt', '{f2} f< {f3}'),
                              (1, 0, 'le', '{f2} f<= {f3}'), (1, 1, 'unord', 'nan({f2}) || nan({f3})')):
        for ta, ct in ((0, 'none'), (1, 'unc')):
            emit_cmp(tab, k, 'fcmp.%s%s{sf}' % (rel, '.unc' if ct == 'unc' else ''), '{p1},{p2}={f2},{f3}',
                     C(k, (37, 40, 4), (33, 33, ra), (36, 36, rb), (12, 12, ta)), P, ct, '(%s)' % cond)
    # fclass.m (op 5)
    fc9 = imm(k, 'FCLASS9', [(20, 26, False), (33, 34, False)], '($0 << 2) | $1')
    cls = ('local e:2 = {f2e} & 0x7fff; local sg:1 = ({f2e} >> 15) != 0; local m:8 = {f2s}; local cl:8 = {c};'
           ' local zero:1 = (e == 0) && (m == 0); local inf:1 = (e == 0x7fff) && (m == 0x8000000000000000);'
           ' local nanv:1 = (e == 0x7fff) && (m != 0x8000000000000000);'
           ' local qn:1 = nanv && ((m >> 62) & 1) != 0; local sn:1 = nanv && ((m >> 62) & 1) == 0;'
           ' local norm:1 = (e != 0x7fff) && (m s< 0) && (e != 0); local unorm:1 = (e != 0x7fff) && !zero && !norm;'
           ' local sgm:1 = (((cl & 1) != 0) && !sg) || (((cl & 2) != 0) && sg);'
           ' local cm:1 = (((cl & 4) != 0) && zero) || (((cl & 8) != 0) && unorm) || (((cl & 16) != 0) && norm)'
           ' || (((cl & 32) != 0) && inf);'
           ' local rel:1 = (sgm && cm) || (((cl & 64) != 0) && sn) || (((cl & 128) != 0) && qn);')
    for ta, ct in ((0, 'none'), (1, 'unc')):
        emit_cmp(tab, k, 'fclass.m%s' % ('.unc' if ct == 'unc' else ''), '{p1},{p2}={f2},{c}',
                 C(k, (37, 40, 5), (12, 12, ta)), dict(P, c=fc9), ct, 'rel', pre=cls)
    # fma family (op 8-D)
    def rnd(pc, e):
        if pc == 's':
            return 'local rs4:4 = float2float(%s); {f1} = float2float(rs4);' % e
        if pc == 'd':
            return 'local rs8:8 = float2float(%s); {f1} = float2float(rs8);' % e
        return '{f1} = %s;' % e
    for op, mn, e in ((8, 'fma', '({f3} f* {f4}) f+ {f2}'), (0xA, 'fms', '({f3} f* {f4}) f- {f2}'),
                      (0xC, 'fnma', '{f2} f- ({f3} f* {f4})')):
        for pc, sel in (('', C(k, (37, 40, op), (36, 36, 0))), ('.s', C(k, (37, 40, op), (36, 36, 1))),
                        ('.d', C(k, (37, 40, op + 1), (36, 36, 0)))):
            p = pc[1:]
            emit_ins(tab, k, mn + pc + '{sf}', '{f1}={f3},{f4},{f2}', sel, F, rnd(p, e))
            # pseudo-ops: fmpy / fadd / fnorm, fsub, fnmpy
            if mn == 'fma':
                emit_ins(tab, k, 'fmpy' + pc + '{sf}', '{f1}={f3},{f4}', sel + C(k, (13, 19, 0)), F,
                         rnd(p, '{f3} f* {f4}'))
                emit_ins(tab, k, 'fadd' + pc + '{sf}', '{f1}={f3},{f2}', sel + C(k, (27, 33, 1)), F,
                         rnd(p, '{f3} f+ {f2}'))
                emit_ins(tab, k, 'fnorm' + pc + '{sf}', '{f1}={f3}', sel + C(k, (27, 33, 1), (13, 19, 0)), F,
                         rnd(p, '{f3}'))
            elif mn == 'fms':
                emit_ins(tab, k, 'fsub' + pc + '{sf}', '{f1}={f3},{f2}', sel + C(k, (27, 33, 1)), F,
                         rnd(p, '{f3} f- {f2}'))
            else:
                emit_ins(tab, k, 'fnmpy' + pc + '{sf}', '{f1}={f3},{f4}', sel + C(k, (13, 19, 0)), F,
                         rnd(p, 'f- ({f3} f* {f4})'))
        pe = e.replace('{f3}', 'fa%(i)d').replace('{f4}', 'fb%(i)d').replace('{f2}', 'fc%(i)d')
        emit_ins(tab, k, 'fp' + mn[1:] + '{sf}', '{f1}={f3},{f4},{f2}', C(k, (37, 40, op + 1), (36, 36, 1)), F, par2(
            lambda i, pe=pe: 'local fa%d:4 = ({f3s} >> %d):4; local fb%d:4 = ({f4s} >> %d):4; local fc%d:4 = ({f2s} >> %d):4;'
            ' local fx%d:4 = %s;' % (i, 32 * i, i, 32 * i, i, 32 * i, i, pe % {'i': i})))
        if mn != 'fms':
            pm = {'fma': 'fa%(i)d f* fb%(i)d', 'fnma': 'f- (fa%(i)d f* fb%(i)d)'}[mn]
            emit_ins(tab, k, {'fma': 'fpmpy', 'fnma': 'fpnmpy'}[mn] + '{sf}', '{f1}={f3},{f4}',
                     C(k, (37, 40, op + 1), (36, 36, 1), (13, 19, 0)), F, par2(
                lambda i, pm=pm: 'local fa%d:4 = ({f3s} >> %d):4; local fb%d:4 = ({f4s} >> %d):4;'
                ' local fx%d:4 = %s;' % (i, 32 * i, i, 32 * i, i, pm % {'i': i})))
    # op E: fselect (x = 0), xma (x = 1)
    emit_ins(tab, k, 'fselect', '{f1}={f3},{f4},{f2}', C(k, (37, 40, 0xE), (36, 36, 0)), F,
             '{f1s} = ({f3s} & {f2s}) | ({f4s} & ~{f2s}); ' + INTRES)
    emit_ins(tab, k, 'xma.l', '{f1}={f3},{f4},{f2}', C(k, (37, 40, 0xE), (36, 36, 1), (34, 35, 0)), F,
             '{f1s} = {f3s} * {f4s} + {f2s}; ' + INTRES)
    emit_ins(tab, k, 'xmpy.l', '{f1}={f3},{f4}', C(k, (37, 40, 0xE), (36, 36, 1), (34, 35, 0), (13, 19, 0)), F,
             '{f1s} = {f3s} * {f4s}; ' + INTRES)
    emit_ins(tab, k, 'xmpy.h', '{f1}={f3},{f4}', C(k, (37, 40, 0xE), (36, 36, 1), (34, 35, 3), (13, 19, 0)), F,
             'local p:16 = sext({f3s}) * sext({f4s}); {f1s} = p(8); ' + INTRES)
    emit_ins(tab, k, 'xmpy.hu', '{f1}={f3},{f4}', C(k, (37, 40, 0xE), (36, 36, 1), (34, 35, 2), (13, 19, 0)), F,
             'local p:16 = zext({f3s}) * zext({f4s}); {f1s} = p(8); ' + INTRES)
    emit_ins(tab, k, 'xma.h', '{f1}={f3},{f4},{f2}', C(k, (37, 40, 0xE), (36, 36, 1), (34, 35, 3)), F,
             'local p:16 = sext({f3s}) * sext({f4s}) + sext({f2s}); {f1s} = p(8); ' + INTRES)
    emit_ins(tab, k, 'xma.hu', '{f1}={f3},{f4},{f2}', C(k, (37, 40, 0xE), (36, 36, 1), (34, 35, 2)), F,
             'local p:16 = zext({f3s}) * zext({f4s}) + zext({f2s}); {f1s} = p(8); ' + INTRES)

# =============================================================================================
# L+X (Section 4.7): one instruction at bundle+6 covering slots 1 and 2 (templates 4, 5).
# The L slot is slot 1 (s1lo + t1 bits 0-38); the X slot uses slot 2's field mapping, its bit 0
# is t1 bit 39 (copied into s2lo by the constructor before the qp tables are resolved).
# =============================================================================================
def gen_LX():
    tab = 'LX'
    k = 2
    qs, qt, qv = qp_tables(2)
    lo39 = rawfld('sl1', 0, 38)
    b39 = rawfld('sl1', 39, 39)
    lines = []
    def xc(*spec):
        return ' & '.join(C(2, *spec))
    def emit(disp, xpat, action, sem, qp=True, lxt=False):
        tail = ' & %s' % qt if qp else ''
        body = ('build %s; ' % qt if qp else '') + sem
        first = '%s & %s' % (lo39, b39)
        pat = '%s ; %s & %s%s' % (first, xpat, qs, tail)
        if lxt:
            pat = '(%s) & %s' % (pat, 'LXT' if lxt is True else lxt)
        lines.append('%s: %s %s is %s [ s2lo = %s; %s ] { %s }' %
                     (tab, disp, qs, pat, b39, action, body))
    r1 = grd(2, 6, 12)
    n1 = natd(2, 6, 12)
    i_, i9d, i5c, ic, i7b = fld(2, 36, 36), fld(2, 27, 35), fld(2, 22, 26), fld(2, 21, 21), fld(2, 13, 19)
    # 64-bit immediates span both tokens: subtables exporting 8-byte constants (an operand
    # defined in the action would be sized by the address space)
    TABLES['LXI'] = ['LXI: val is %s ; %s & %s & %s & %s & %s [ val = (%s << 63) | (((%s << 2) | s1lo) << 22) | '
                     '(%s << 21) | (%s << 16) | (%s << 7) | %s; ] { export *[const]:8 val; }' %
                     (lo39, i_, ic, i5c, i9d, i7b, i_, lo39, ic, i5c, i9d, i7b)]
    emit('"movl" %s"="LXI' % r1, '%s & %s & %s' % (xc((37, 40, 6), (20, 20, 0)), r1, n1),
         '', '%s = LXI; %s = 0;' % (r1, n1), lxt='LXI')
    i20b = fld(2, 13, 32)
    bwh, ph, dh = BWH(2), PH(2), DH(2)
    tgt = '(inst_start - (inst_start & 15) - 6) + ((((%s << 59) | (%s << 20) | %s)) << 4)' % (i_, lo39, i20b)
    # inst_start of the L+X instruction is bundle+6
    tgt = '(inst_start - 6) + ((%s << 63) | (%s << 24) | (%s << 4))' % (i_, lo39, i20b)
    TABLES['LXT'] = ['LXT: target64 is %s ; %s & %s [ target64 = %s; ] { export *:8 target64; }' % (lo39, i_, i20b, tgt)]
    brlc = 'BRLC'
    TABLES[brlc] = ['%s: "brl" is s2lo=0 & %s=0 & %s=0 { }' % (brlc, fld(2, 1, 5), fld(2, 33, 34)),
                    '%s: "brl.cond"^%s is %s { }' % (brlc, bwh, bwh)]
    emit('%s^%s^%s LXT' % (brlc, ph, dh),
         '%s & %s & %s & %s & %s' % (xc((37, 40, 0xC), (6, 8, 0)), bwh, ph, dh, brlc),
         '', 'goto LXT;', lxt=True)
    b1 = brr(2, 6, 8)
    args, argr = arg_tables()
    emit('"brl.call"^%s^%s^%s %s"="LXT' % (bwh, ph, dh, b1),
         '%s & %s & %s & %s & %s & %s & %s & RSPILL & %s' % (xc((37, 40, 0xD)), bwh, ph, dh, b1, args, argr,
                                                                   NB(2)),
         '', '%s = inst_start + 10; ar.pfs = (ar.ec << 52) | cfm; %s call LXT; build ARGR;' % (b1, RSE_CALL),
         lxt=True)
    i20a = fld(2, 6, 25)
    TABLES['LXB'] = ['LXB: val is %s ; %s & %s [ val = (((%s << 2) | s1lo) << 21) | (%s << 20) | %s; ] '
                     '{ export *[const]:8 val; }' % (lo39, i_, i20a, lo39, i_, i20a)]
    emit('"break.x" LXB', xc((37, 40, 0), (33, 35, 0), (27, 32, 0)), '', 'ia64_break(LXB);',
         lxt='LXB')
    emit('"nop.x" LXB', xc((37, 40, 0), (33, 35, 0), (27, 32, 1), (26, 26, 0)), '', 'local nopmark:1 = 0;',
         lxt='LXB')
    emit('"hint.x" LXB', xc((37, 40, 0), (33, 35, 0), (27, 32, 1), (26, 26, 1)), '', 'ia64_hint(LXB);', lxt='LXB')
    UNITS[tab] = lines

def gen_roots():
    """Root constructors: one per slot (plus the L+X pair). The unit table for the slot is chosen
    from the template by U0/U1/U2 (Table 4-2); reserved templates match nothing."""
    out = []
    t0 = rawfld('sl0', 0, 4)
    s1 = rawfld('sl0', 46, 47)
    b39 = rawfld('sl1', 39, 39)
    for k in (0, 1, 2):
        units = {}
        for t, us in sorted(TEMPLATES.items()):
            if us[k] != 'L' and not (k == 2 and us[1] == 'L'):
                units.setdefault(us[k], []).append(t)
        for u, ts in sorted(units.items()):
            out.append('U%d: ^%s_%d is (%s) & %s_%d { build %s_%d; }' %
                       (k, u, k, ' | '.join('tmpl=%d' % t for t in ts), u, k, u, k))
    out.append(':^U0 is slot=0 & %s & %s & U0 [ tmpl = %s; s1lo = %s; slot = 1; '
               'globalset(inst_next, tmpl); globalset(inst_next, s1lo); globalset(inst_next, slot); ] '
               '{ build U0; }' % (t0, s1, t0, s1))
    lx = [t for t, us in TEMPLATES.items() if us[1] == 'L']
    other = [t for t, us in sorted(TEMPLATES.items()) if us[1] != 'L']
    out.append(':^LX is slot=1 & (%s) & LX { build LX; }' % ' | '.join('tmpl=%d' % t for t in lx))
    out.append(':^U1 is slot=1 & (%s) & %s & U1 [ slot = 2; s2lo = %s; globalset(inst_next, tmpl); '
               'globalset(inst_next, s2lo); globalset(inst_next, slot); ] { build U1; }' %
               (' | '.join('tmpl=%d' % t for t in other), b39, b39))
    out.append(':^U2 is slot=2 & U2 { build U2; }')

    return out

def _balanced(text, i):
    """end index (exclusive) of the parenthesised expression starting at text[i] == '('"""
    depth = 0
    for j in range(i, len(text)):
        if text[j] == '(':
            depth += 1
        elif text[j] == ')':
            depth -= 1
            if depth == 0:
                return j + 1
    raise ValueError(text)

def to32(body):
    """Rewrite a p-code body for a 32-bit address space (HP-UX ILP32): memory addresses and
    indirect branch targets are 64-bit values here; truncate them to 32 bits (dropping the region
    bits that addp4 sets) through temporaries hoisted in front of each statement."""
    import re
    out = []
    n = [0]
    for stmt in body.split(';'):
        m = re.match(r'(\s*(?:<\w+>\s*)*)(.*)$', stmt, re.S)
        lbl, core = m.group(1), m.group(2)
        if core.strip().startswith('export'):
            out.append(stmt)
            continue
        hoist = []
        res = ''
        i = 0
        while i < len(core):
            d = re.compile(r'\*:(\d+) ').match(core, i)
            g = re.compile(r'(goto|call|return) \[').match(core, i)
            if d:
                j = d.end()
                if core[j] == '(':
                    e = _balanced(core, j)
                else:
                    e = re.compile(r'[\w.]+').match(core, j).end()
                k = n[0]
                n[0] += 1
                hoist.append('local _p%d:8 = %s; local _q%d:4 = _p%d:4;' % (k, core[j:e], k, k))
                res += '*:%s _q%d' % (d.group(1), k)
                i = e
            elif g:
                j = g.end()
                e = core.index(']', j)
                k = n[0]
                n[0] += 1
                hoist.append('local _q%d:4 = %s:4;' % (k, core[j:e].strip()))
                res += '%s [_q%d]' % (g.group(1), k)
                i = e + 1
            else:
                res += core[i]
                i += 1
        out.append(lbl + ' '.join(hoist) + (' ' if hoist else '') + res)
    return ';'.join(out)

def body32(line):
    """apply to32 to the semantic section { ... } of a constructor line"""
    if '{' not in line:
        return line
    a = line.index('{')
    b = line.rindex('}')
    return line[:a + 1] + to32(line[a + 1:b]) + line[b:]

def main():
    outdir = sys.argv[1] if len(sys.argv) > 1 else '.'
    for k in (0, 1, 2):
        qp_tables(k)
    # unit tables per slot
    gen_A(0, 'M_0'); gen_M(0, 'M_0'); gen_B(0, 'B_0')
    gen_A(1, 'M_1'); gen_M(1, 'M_1'); gen_A(1, 'I_1'); gen_I(1, 'I_1'); gen_F(1, 'F_1'); gen_B(1, 'B_1')
    gen_A(2, 'I_2'); gen_I(2, 'I_2'); gen_F(2, 'F_2'); gen_B(2, 'B_2')
    gen_LX()
    roots = gen_roots()
    o = ['# Generated by tools/gen_ia64.py -- do not edit', '']
    toks = {'sl0': 48, 'sl1': 40, 'sl2': 40}
    for tok, size in toks.items():
        o.append('define token %s(%d) endian=little' % (tok, size))
        for name, (tk, lo, hi, sg) in sorted(FIELDS.items(), key=lambda x: (x[1][1], x[1][2], x[0])):
            if tk == tok:
                o.append('  %s=(%d,%d)%s' % (name, lo, hi, ' signed' if sg else ''))
        o.append(';')
    o.append('')
    groups = {}
    for (field, kind), names in ATTACHED.items():
        groups.setdefault((kind, tuple(names)), []).append(field)
    for (kind, names), fields in sorted(groups.items(), key=lambda x: x[1][0]):
        o.append('attach %s [ %s ] [ %s ];' % (kind, ' '.join(sorted(fields)), ' '.join(names)))
    o.append('')
    for name, lines in TABLES.items():
        o.extend(lines)
        o.append('')
    for name, lines in UNITS.items():
        o.append('# ---- %s: %d constructors' % (name, len(lines)))
        o.extend(lines)
        o.append('')
    o.extend(roots)
    with open(os.path.join(outdir, 'ia64_gen.sinc'), 'w') as f:
        f.write('\n'.join(o) + '\n')
    # the same tables for a 32-bit data address space (ILP32)
    o32 = [body32(l) if l and not l.startswith(('#', 'define', 'attach', '  ', ';')) else l for l in o]
    with open(os.path.join(outdir, 'ia64_gen32.sinc'), 'w') as f:
        f.write('\n'.join(o32) + '\n')
    with open(os.path.join(outdir, 'ia64_regs.sinc'), 'w') as f:
        f.write(regs_sinc())

if __name__ == '__main__':
    main()
