class Op:
    """an operand symbol plus the pattern atoms that bind it"""
    def __init__(self, sym):
        self.sym = sym

def disp(fmt, ops):
    """translate '{r1}={r2},{r3}' into SLEIGH display pieces"""
    out = []
    i = 0
    lit = ''
    while i < len(fmt):
        if fmt[i] == '{':
            j = fmt.index('}', i)
            if lit:
                out.append('"%s"' % lit)
                lit = ''
            out.append(ops[fmt[i + 1:j]])
            i = j + 1
        else:
            lit += fmt[i]
            i += 1
    if lit:
        out.append('"%s"' % lit)
    return out

def subst(text, ops):
    def rep(m):
        return ops[m.group(1)]
    import re
    return re.sub(r'\{(\w+)\}', rep, text)

def mnem(mn, ops):
    """'ld8{ldh}' -> ld8^LDH"""
    import re
    parts = re.split(r'(\{\w+\})', mn)
    res = []
    for p in parts:
        if not p:
            continue
        if p.startswith('{'):
            res.append(ops[p[1:-1]])
        else:
            res.append('"%s"' % p)
    return '^'.join(res)

def emit_ins(tab, k, mn, fmt, atoms, ops, sem, qp='test', extra_syms=()):
    """tab: unit table name; k: slot (0/1/2) whose QS/QT/QV tables apply."""
    qs, qt, qv = qp_tables(k)
    ops = dict(ops)
    ops['qv'] = qv
    used = []
    def use(sym):
        if sym not in used:
            used.append(sym)
    import re
    for name in re.findall(r'\{(\w+)\}', mn + fmt + sem):
        use(ops[name])
    for s in extra_syms:
        use(s)
    d = mnem(mn, ops)
    pieces = disp(fmt, ops) if fmt else []
    dq = 'ST%d' % k if qp == 'stop' else qs
    display = d + (' ' + '^'.join(pieces) if pieces else '') + ' ' + dq
    pat = list(atoms) + [s for s in used if s not in re.split(r'[=&\s]+', ' '.join(atoms))]
    pat.append(dq)
    # Instructions without semantics (nop, hints, lfetch, brp) still get one p-code op: the
    # decompiler labels a jump-table target block with the address of its first p-code op, and
    # a target bundle starting with nops must keep its bundle address.
    body = subst(sem, ops) if sem.strip() else 'local nopmark:1 = 0;'
    body = re.sub(r'local (\w+):(\d+) = \(([^()]+) >> (\d+)\):(\d+);',
                  r'local \1_t:8 = \3 >> \4; local \1:\2 = \1_t:\5;', body)
    if qp == 'test':
        pat.append(qt)
        body = 'build %s; ' % qt + body
    UNITS.setdefault(tab, []).append('%s: %s is %s { %s }' % (tab, display, ' & '.join(pat), body))

def C(k, *spec):
    """constraint atoms from (lo, hi, val) triples on slot k"""
    atoms = []
    for lo, hi, v in spec:
        atoms += cons(k, lo, hi, v)
    return atoms

# Completer tables -------------------------------------------------------------------------
def completer(k, lo, hi, names, prefix):
    f = fld(k, lo, hi)
    name = '%s%d' % (prefix, k)
    lines = []
    for v, n in enumerate(names):
        if n is None:
            continue
        lines.append('%s: %s is %s=%d { }' % (name, '"%s"' % n if n else '', f, v))
    return table(name, lines)

def completer3(k, b3, names, prefix):
    """hint completer from bits 29:28 plus a third bit (b3) that GNU objdump decodes as the
    data-access hints .d4-.d7 of later processors (an ignored field in SDM 2.3)"""
    f, g = fld(k, 28, 29), fld(k, b3, b3)
    name = '%s%d' % (prefix, k)
    lines = []
    for v, n in enumerate(names):
        lines.append('%s: %s is %s=%d & %s=%d { }' % (name, '"%s"' % n if n else '', f, v & 3, g, v >> 2))
    return table(name, lines)

