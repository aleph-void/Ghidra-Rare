    ops2 = dict(ops, c=inc)
    for x6, mn in ((0x12, 'fetchadd4.acq'), (0x13, 'fetchadd8.acq'), (0x16, 'fetchadd4.rel'), (0x17, 'fetchadd8.rel')):
        sz = 4 if '4' in mn else 8
