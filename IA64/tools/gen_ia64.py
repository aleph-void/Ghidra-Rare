#!/usr/bin/env python3
"""Generate the IA-64 SLEIGH tables (data/languages/ia64_gen.sinc and ia64_regs.sinc).

Written from the Intel Itanium Architecture Software Developer's Manual, rev. 2.3, volume 3,
chapter 4 (instruction formats, opcode extension tables, Table 4-74 immediate formation) and the
instruction descriptions in chapter 2. GNU objdump was used only as a black-box decode reference;
no binutils source or opcode table was read.

Model (see README.md):
  * Each 41-bit slot is one Ghidra instruction. Slot 0 sits at bundle+0 (6 bytes), slot 1 at
    bundle+6 (5 bytes) and slot 2 at bundle+11 (5 bytes). An MLX bundle's L+X pair is one
    instruction at bundle+6 (10 bytes).
  * Bundle bits are numbered 0-127 little-endian. Slot 0 = bits 5-45, slot 1 = 46-86,
    slot 2 = 87-127. Slot 0's 6 bytes hold the template and slot 1 bits 0-1; slot 1's 5 bytes
    hold slot 2 bit 0. Those bits travel to the next slot in noflow context fields (tmpl, s1lo,
    s2lo) set with globalset; "slot" says which slot an address holds.
Usage: gen_ia64.py <outdir>   (writes ia64_regs.sinc and ia64_gen.sinc)
"""
import sys, os

