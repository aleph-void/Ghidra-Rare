# ---------------------------------------------------------------------------------------------
# Tokens and fields
# Slot k bit b lives in:
#   slot 0: token t0 (48 bits, bundle bytes 0-5), bit b+5
#   slot 1: token t1 (40 bits, bytes 6-10), bit b-2 (b >= 2); bits 0-1 in context s1lo
#   slot 2: token t2 (40 bits, bytes 11-15), bit b-1 (b >= 1); bit 0 in context s2lo
# The X slot of an MLX pair uses slot 2's mapping (s2lo is set from t1 bit 39 by the L+X
# constructor itself).
# ---------------------------------------------------------------------------------------------
TOK = {0: ('sl0', 48, 5), 1: ('sl1', 40, -2), 2: ('sl2', 40, -1)}
FIELDS = {}      # name -> (token, lo, hi, signed)

def fld(slot, lo, hi, signed=False):
    tok, size, off = TOK[slot]
    tlo, thi = lo + off, hi + off
    assert tlo >= 0 and thi < size, (slot, lo, hi)
    name = 's%d_%d_%d%s' % (slot, lo, hi, 's' if signed else '')
    FIELDS[name] = (tok, tlo, thi, signed)
    return name

def rawfld(tok, lo, hi, signed=False):
    name = '%s_%d_%d%s' % (tok, lo, hi, 's' if signed else '')
    FIELDS[name] = (tok, lo, hi, signed)
    return name

LOWCTX = {1: ('s1lo', 2), 2: ('s2lo', 1)}

def cons(slot, lo, hi, val):
    """pattern atoms constraining slot bits lo..hi to val"""
    atoms = []
    if slot in LOWCTX and lo < LOWCTX[slot][1]:
        ctx, n = LOWCTX[slot]
        top = min(hi, n - 1)
        part = (val >> 0) & ((1 << (top - lo + 1)) - 1)
        if lo == 0 and top == n - 1:
            atoms.append('%s=%d' % (ctx, part))
        else:
            raise ValueError('partial low-context field')
        if hi >= n:
            atoms.append('%s=%d' % (fld(slot, n, hi), val >> (n - lo)))
        return atoms
    return ['%s=%d' % (fld(slot, lo, hi), val)]

