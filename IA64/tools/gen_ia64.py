# Immediates (Table 4-74) ----------------------------------------------------------------
def imm(k, name, fields, expr, kind='const'):
    """fields: list of (lo, hi, signed); expr uses $0, $1 ... for the fields"""
    syms = [fld(k, lo, hi, sg) for lo, hi, sg in fields]
    e = expr
    for i, s in enumerate(syms):
        e = e.replace('$%d' % i, s)
    tname = '%s_%d' % (name, k)
    if kind == 'const':
        body = '{ export *[const]:8 val; }'
    else:
        body = '{ export *:8 val; }'
    if expr == '$0':
        return table(tname, ['%s: %s is %s %s' % (tname, syms[0], syms[0], body.replace('val', syms[0]))])
    return table(tname, ['%s: val is %s [ val = %s; ] %s' % (tname, ' & '.join(syms), e, body)])

