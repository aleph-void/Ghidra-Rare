CMPREL = {  # (op, x2 is cmp4) -> relation on a, b
    0xC: 'lt', 0xD: 'ltu', 0xE: 'eq'}

def relexpr(rel, a, b):
    return {'lt': '(%s s< %s)' % (a, b), 'ltu': '(%s < %s)' % (a, b), 'eq': '(%s == %s)' % (a, b),
            'ne': '(%s != %s)' % (a, b), 'gt': '(%s s> %s)' % (a, b), 'le': '(%s s<= %s)' % (a, b),
            'ge': '(%s s>= %s)' % (a, b), 'z': '(%s == 0)' % a, 'nz': '(%s != 0)' % a}[rel]

def pred_write(ctype, cond):
    """p-code for a predicate-writing compare of the given type; {p1},{p2},{qv} placeholders.
    'none' and 'unc' are emitted without the QT test (see the callers)."""
    if ctype == 'none':
        # Each predicate is written from the comparison directly (no shared temporary): the
        # decompiler's switch-guard analysis pulls a branch condition back through only two ops
        # (predicate test, then its definition) to reach the compared register.
        if 'ia64_' in cond:  # a user-op result needs a sized temporary
            return 'local c:1 = %s; {p1} = c; {p2} = !c;' % cond
        return '{p1} = %s; {p2} = !%s;' % (cond, cond)
    if ctype == 'unc':
        return ('local c:1 = %s; local q:1 = {qv}; {p1} = q && c; {p2} = q && !c;' % cond)
    if ctype == 'and':
        return 'local c:1 = %s; if (c) goto inst_next; {p1} = 0; {p2} = 0;' % cond
    if ctype == 'or':
        return 'local c:1 = %s; if (!c) goto inst_next; {p1} = 1; {p2} = 1;' % cond
    if ctype == 'or.andcm':
        return 'local c:1 = %s; if (!c) goto inst_next; {p1} = 1; {p2} = 0;' % cond
    raise ValueError(ctype)

def emit_cmp(tab, k, mn, fmt, atoms, ops, ctype, cond, pre=''):
    sem = pre + (' ' if pre else '') + pred_write(ctype, cond)
    emit_ins(tab, k, mn, fmt, atoms, ops, sem, qp='none' if ctype == 'unc' else 'test')

def gen_A(k, tab):
    R = regs3(k)
    alu = [  # x4, x2b, mnemonic, fmt, sem
        (0, 0, 'add', '{r1}={r2},{r3}', '{r1} = {r2} + {r3};'),
        (0, 1, 'add', '{r1}={r2},{r3},1', '{r1} = {r2} + {r3} + 1;'),
        (1, 1, 'sub', '{r1}={r2},{r3}', '{r1} = {r2} - {r3};'),
        (1, 0, 'sub', '{r1}={r2},{r3},1', '{r1} = {r2} - {r3} - 1;'),
        (2, 0, 'addp4', '{r1}={r2},{r3}',
         'local t:8 = {r2} + {r3}; {r1} = zext(t:4) | ((({r3} >> 30) & 3) << 61);'),
        (3, 0, 'and', '{r1}={r2},{r3}', '{r1} = {r2} & {r3};'),
        (3, 1, 'andcm', '{r1}={r2},{r3}', '{r1} = {r2} & ~{r3};'),
        (3, 2, 'or', '{r1}={r2},{r3}', '{r1} = {r2} | {r3};'),
        (3, 3, 'xor', '{r1}={r2},{r3}', '{r1} = {r2} ^ {r3};'),
    ]
    for x4, x2b, mn, fmt, sem in alu:
        emit_ins(tab, k, mn, fmt, C(k, (37, 40, 8), (34, 35, 0), (33, 33, 0), (29, 32, x4), (27, 28, x2b)),
                 R, sem + ' {n1} = {n2} | {n3};')
    # A2 shladd / shladdp4 (count2 = ct2d + 1)
    cnt = imm(k, 'CNT2', [(27, 28, False)], '$0 + 1')
    ops = dict(R, c=cnt)
    emit_ins(tab, k, 'shladd', '{r1}={r2},{c},{r3}', C(k, (37, 40, 8), (34, 35, 0), (33, 33, 0), (29, 32, 4)),
             ops, '{r1} = ({r2} << {c}) + {r3}; {n1} = {n2} | {n3};')
    emit_ins(tab, k, 'shladdp4', '{r1}={r2},{c},{r3}', C(k, (37, 40, 8), (34, 35, 0), (33, 33, 0), (29, 32, 6)),
             ops, 'local t:8 = ({r2} << {c}) + {r3}; {r1} = zext(t:4) | ((({r3} >> 30) & 3) << 61);'
             ' {n1} = {n2} | {n3};')
    # A3 imm8 forms
    ops = dict(R, i=IMM8(k))
    for x4, x2b, mn, sem in [(9, 1, 'sub', '{r1} = {i} - {r3};'), (0xB, 0, 'and', '{r1} = {i} & {r3};'),
                             (0xB, 1, 'andcm', '{r1} = {i} & ~{r3};'), (0xB, 2, 'or', '{r1} = {i} | {r3};'),
                             (0xB, 3, 'xor', '{r1} = {i} ^ {r3};')]:
        emit_ins(tab, k, mn, '{r1}={i},{r3}', C(k, (37, 40, 8), (34, 35, 0), (33, 33, 0), (29, 32, x4), (27, 28, x2b)),
                 ops, sem + ' {n1} = {n3};')
    # A4 adds / addp4 imm14; "mov r1=r3" when imm14 = 0
    ops = dict(R, i=IMM14(k))
    zero14 = C(k, (36, 36, 0), (27, 32, 0), (13, 19, 0))
    emit_ins(tab, k, 'mov', '{r1}={r3}', C(k, (37, 40, 8), (34, 35, 2), (33, 33, 0)) + zero14, ops,
             '{r1} = {r3}; {n1} = {n3};')
    emit_ins(tab, k, 'adds', '{r1}={i},{r3}', C(k, (37, 40, 8), (34, 35, 2), (33, 33, 0)), ops,
             '{r1} = {i} + {r3}; {n1} = {n3};')
    emit_ins(tab, k, 'addp4', '{r1}={i},{r3}', C(k, (37, 40, 8), (34, 35, 3), (33, 33, 0)), ops,
             'local t:8 = {i} + {r3}; {r1} = zext(t:4) | ((({r3} >> 30) & 3) << 61); {n1} = {n3};')
    # A5 addl (r3 is 2 bits); "mov r1=imm22" when r3 = r0
    # r3 = r0 is the mov pseudo-op, so addl's r3 is r1-r3 here
    ops = dict(R, i=IMM22(k), r3=grd(k, 20, 21), n3=natd(k, 20, 21))
    emit_ins(tab, k, 'mov', '{r1}={i}', C(k, (37, 40, 9), (20, 21, 0)), ops, '{r1} = {i}; {n1} = 0;')
    emit_ins(tab, k, 'addl', '{r1}={i},{r3}', C(k, (37, 40, 9)), ops, '{r1} = {i} + {r3}; {n1} = {n3};')
    # A6/A7/A8 compares
    P = dict(p1=prd(k, 6, 11), p2=prd(k, 27, 32))
    for op, base in ((0xC, 'lt'), (0xD, 'ltu'), (0xE, 'eq')):
        for x2, w in ((0, ''), (1, '4')):
            a = '{r2}' if not w else '{r2}:4'
            b = '{r3}' if not w else '{r3}:4'
            ops = dict(R, **P)
            # A6 tb=0 ta=0: c=0 none, c=1 unc
            for c, ct in ((0, 'none'), (1, 'unc')):
                mn = 'cmp%s.%s%s' % (w, base, '.unc' if ct == 'unc' else '')
                emit_cmp(tab, k, mn, '{p1},{p2}={r2},{r3}',
                         C(k, (37, 40, op), (36, 36, 0), (34, 35, x2), (33, 33, 0), (12, 12, c)), ops, ct,
                         relexpr(base, a, b))
            # A6 tb=0 ta=1: eq/ne parallel compares
            ptype = {0xC: 'and', 0xD: 'or', 0xE: 'or.andcm'}[op]
            for c, rel in ((0, 'eq'), (1, 'ne')):
                emit_cmp(tab, k, 'cmp%s.%s.%s' % (w, rel, ptype), '{p1},{p2}={r2},{r3}',
                         C(k, (37, 40, op), (36, 36, 0), (34, 35, x2), (33, 33, 1), (12, 12, c)), ops, ptype,
                         relexpr(rel, a, b))
            # A7 tb=1: compare r0 with r3
            for ta, c, rel in ((0, 0, 'gt'), (0, 1, 'le'), (1, 0, 'ge'), (1, 1, 'lt')):
                emit_cmp(tab, k, 'cmp%s.%s.%s' % (w, rel, ptype), '{p1},{p2}=r0,{r3}',
                         C(k, (37, 40, op), (36, 36, 1), (34, 35, x2), (33, 33, ta), (12, 12, c)),
                         ops, ptype, relexpr(rel, '0:%d' % (4 if w else 8), b))
            # A8 imm8: x2 = 2 (cmp) / 3 (cmp4)
            ops8 = dict(ops, i=IMM8(k))
            ai = '{i}' if not w else '{i}:4'
            for c, ct in ((0, 'none'), (1, 'unc')):
                mn = 'cmp%s.%s%s' % (w, base, '.unc' if ct == 'unc' else '')
                emit_cmp(tab, k, mn, '{p1},{p2}={i},{r3}',
                         C(k, (37, 40, op), (34, 35, x2 + 2), (33, 33, 0), (12, 12, c)), ops8, ct,
                         relexpr(base, ai, b))
            for c, rel in ((0, 'eq'), (1, 'ne')):
                emit_cmp(tab, k, 'cmp%s.%s.%s' % (w, rel, ptype), '{p1},{p2}={i},{r3}',
                         C(k, (37, 40, op), (34, 35, x2 + 2), (33, 33, 1), (12, 12, c)), ops8, ptype,
                         relexpr(rel, ai, b))
    gen_A_mm(k, tab, R)

def lanes(sz):
    return 8 // sz

def mm_binop(sz, fn, srcs=('{r2}', '{r3}'), nat=True):
    """p-code applying a lane function to each sz-byte lane of the sources.
    fn(i, a, b, sz) returns statements that leave the lane result in local r<i> (sz bytes)."""
    n = lanes(sz)
    s = 'local a:8 = %s; local b:8 = %s; local r:8 = 0;' % srcs
    for i in range(n):
        s += ' local ua%d:%d = a(%d); local ub%d:%d = b(%d);' % (i, sz, i * sz, i, sz, i * sz)
        s += ' ' + fn(i, 'ua%d' % i, 'ub%d' % i, sz)
        s += ' r = r | (zext(ur%d) << %d);' % (i, i * sz * 8)
    return s + ' {r1} = r;' + (' {n1} = {n2} | {n3};' if nat else '')

def clamp(i, t, w, sz, lo, hi):
    """statements: r<i>:sz = t (w bytes, signed) clamped to [lo, hi]"""
    m = (1 << (8 * sz)) - 1
    return ('local ut%d:%d = %s; local ul%d:1 = ut%d s< %d; local uh%d:1 = ut%d s> %d;'
            ' local ur%d:%d = ut%d:%d * zext(!ul%d && !uh%d) + %d * zext(ul%d) + %d * zext(uh%d);' %
            (i, w, t, i, i, lo, i, i, hi, i, sz, i, sz, i, i, lo & m, i, hi & m, i))

def lane_sat(kind, op):
    def f(i, a, b, sz):
        w = 2 * sz
        if kind == 'sss':
            lo, hi = -(1 << (8 * sz - 1)), (1 << (8 * sz - 1)) - 1
            ea, eb = 'sext(%s)' % a, 'sext(%s)' % b
        elif kind == 'uuu':
            lo, hi = 0, (1 << (8 * sz)) - 1
            ea, eb = 'zext(%s)' % a, 'zext(%s)' % b
        else:  # uus: r2 unsigned, r3 signed, unsigned result
            lo, hi = 0, (1 << (8 * sz)) - 1
            ea, eb = 'zext(%s)' % a, 'sext(%s)' % b
        return clamp(i, '%s %s %s' % (ea, op, eb), w, sz, lo, hi)
    return f

def gen_A_mm(k, tab, R):
    # A9 multimedia ALU: op 8, x2a = 1; (za, zb) = size
    sizes = {1: (0, 0), 2: (0, 1), 4: (1, 0)}
    def base(sz, x4, x2b=None):
        za, zb = sizes[sz]
        c = [(37, 40, 8), (34, 35, 1), (36, 36, za), (33, 33, zb), (29, 32, x4)]
        if x2b is not None:
            c.append((27, 28, x2b))
        return C(k, *c)
    for sz in (1, 2, 4):
        n = str(sz)
        emit_ins(tab, k, 'padd' + n, '{r1}={r2},{r3}', base(sz, 0, 0), R,
                 mm_binop(sz, lambda i, a, b, s: 'local ur%d:%d = %s + %s;' % (i, s, a, b)))
        emit_ins(tab, k, 'psub' + n, '{r1}={r2},{r3}', base(sz, 1, 0), R,
                 mm_binop(sz, lambda i, a, b, s: 'local ur%d:%d = %s - %s;' % (i, s, a, b)))
        emit_ins(tab, k, 'pcmp%s.eq' % n, '{r1}={r2},{r3}', base(sz, 9, 0), R,
                 mm_binop(sz, lambda i, a, b, s: 'local ur%d:%d = 0 - zext(%s == %s);' % (i, s, a, b)))
        emit_ins(tab, k, 'pcmp%s.gt' % n, '{r1}={r2},{r3}', base(sz, 9, 1), R,
                 mm_binop(sz, lambda i, a, b, s: 'local ur%d:%d = 0 - zext(%s s> %s);' % (i, s, a, b)))
        if sz == 4:
            continue
        for x2b, kind in ((1, 'sss'), (2, 'uuu'), (3, 'uus')):
            for x4, opn, op in ((0, 'padd', '+'), (1, 'psub', '-')):
                emit_ins(tab, k, '%s%s.%s' % (opn, n, kind), '{r1}={r2},{r3}', base(sz, x4, x2b), R,
                         mm_binop(sz, lane_sat(kind, op)))
        w = 2 * sz
        emit_ins(tab, k, 'pavg' + n, '{r1}={r2},{r3}', base(sz, 2, 2), R,
                 mm_binop(sz, lambda i, a, b, s: 'local ut%d:%d = zext(%s) + zext(%s); '
                          'local uv%d:%d = (ut%d >> 1) | (ut%d & 1); local ur%d:%d = uv%d:%d;' % (i, 2 * s, a, b, i, 2 * s, i, i, i, s, i, s)))
        emit_ins(tab, k, 'pavg%s.raz' % n, '{r1}={r2},{r3}', base(sz, 2, 3), R,
                 mm_binop(sz, lambda i, a, b, s: 'local ut%d:%d = zext(%s) + zext(%s) + 1; '
                          'local uv%d:%d = ut%d >> 1; local ur%d:%d = uv%d:%d;' % (i, 2 * s, a, b, i, 2 * s, i, i, s, i, s)))
        emit_ins(tab, k, 'pavgsub' + n, '{r1}={r2},{r3}', base(sz, 3, 2), R,
                 mm_binop(sz, lambda i, a, b, s: 'local ut%d:%d = (zext(%s) - zext(%s)) & %d; '
                          'local uv%d:%d = (ut%d >> 1) | (ut%d & 1); local ur%d:%d = uv%d:%d;' %
                          (i, 2 * s, a, b, (1 << (8 * s + 1)) - 1, i, 2 * s, i, i, i, s, i, s)))
    # A10 pshladd2 / pshradd2 (count2 = ct2d + 1; ct2d = 3 is reserved)
    ops = dict(R, c=imm(k, 'CNT2', [(27, 28, False)], '$0 + 1'))
    for x4, mn, sh in ((4, 'pshladd2', '<<'), (6, 'pshradd2', 's>>')):
        emit_ins(tab, k, mn, '{r1}={r2},{c},{r3}', base(2, x4) + C(k, (28, 28, 0)) if False else
                 base(2, x4), ops,
                 mm_binop(2, lambda i, a, b, s, sh=sh: clamp(i, '(sext(%s) %s {c}) + sext(%s)' % (a, sh, b),
                                                            4, 2, -32768, 32767)))


BREAK_SEM = 'ia64_break({i});'

def emit_break(tab, k, mn, atoms, ops):
    """break: a trap (pcodeop that falls through, like other Ghidra trap models; the Linux
    system call is break 0x100000). Keeping the fall-through matters: GCC puts break 0 after
    calls that do not return, and Ghidra's non-returning-function discovery follows the
    fall-through after such calls."""
    emit_ins(tab, k, mn, '{i}', atoms, ops, BREAK_SEM)

