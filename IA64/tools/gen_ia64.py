# Operand tables (one set per slot)
# ---------------------------------------------------------------------------------------------
TABLES = {}       # name -> list of constructor lines
ATTACH = []       # (kind, [fields], [names])
ATTACHED = {}

def table(name, lines):
    if name not in TABLES:
        TABLES[name] = lines
    return name

def attach_regs(field, names, kind='variables'):
    tok, lo, hi, sg = FIELDS[field]
    names = names[:1 << (hi - lo + 1)]
    key = (field, kind)
    if key not in ATTACHED:
        ATTACHED[key] = names
    return field

def grd(slot, lo, hi):
    """general register destination: field with attached registers"""
    f = fld(slot, lo, hi)
    fa = f + '_gr'
    FIELDS[fa] = FIELDS[f]
    attach_regs(fa, GR)
    return fa

def grs(slot, lo, hi):
    """general register source: r0 reads as 0"""
    f = grd(slot, lo, hi)
    name = 'GRS%d_%d_%d' % (slot, lo, hi)
    return table(name, [
        '%s: "r0" is %s=0 { export 0:8; }' % (name, f),
        '%s: %s is %s { export %s; }' % (name, f, f, f)])

