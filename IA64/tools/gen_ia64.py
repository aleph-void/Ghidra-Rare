def regs_sinc():
    o = []
    o.append('# Generated by tools/gen_ia64.py -- do not edit')
    o.append('# General registers r0-r127 (r0 reads as 0 through the operand tables)')
    o.append('define register offset=0x0000 size=8 [ %s ];' % ' '.join(GR))
    o.append('# NaT bits of the general registers')
    o.append('define register offset=0x0400 size=1 [ %s ];' % ' '.join(NAT))
    o.append('# Predicate registers p0-p63 (one byte each, 0 or 1); pzero takes writes to p0')
    o.append('define register offset=0x0500 size=1 [ %s pzero ];' % ' '.join(PR))
    o.append('define register offset=0x0600 size=8 [ %s ];' % ' '.join(BR))
    o.append('define register offset=0x0800 size=8 [ %s ];' % ' '.join(AR))
    o.append('define register offset=0x0c00 size=8 [ %s ];' % ' '.join(CR))
    o.append('# Floating-point registers, modelled in the 80-bit double-extended format, one per')
    o.append('# 16 bytes; fNs is the 64-bit significand and fNe the sign and 15-bit exponent.')
    for i in range(128):
        o.append('define register offset=0x%04x size=10 [ f%d ];' % (0x1000 + 16 * i, i))
    o.append('@if ENDIAN == "big"')
    for i in range(128):
        o.append('define register offset=0x%04x size=8 [ f%ds ];' % (0x1000 + 16 * i + 2, i))
        o.append('define register offset=0x%04x size=2 [ f%de ];' % (0x1000 + 16 * i, i))
    o.append('@else')
    for i in range(128):
        o.append('define register offset=0x%04x size=8 [ f%ds ];' % (0x1000 + 16 * i, i))
        o.append('define register offset=0x%04x size=2 [ f%de ];' % (0x1000 + 16 * i + 8, i))
    o.append('@endif')
    return '\n'.join(o) + '\n'

