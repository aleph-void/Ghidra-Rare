#!/usr/bin/env python3
"""Write sass.ldefs, sass.opinion and the per-variant .slaspec files.

Each language variant has one generated instruction file sass_<V>.sinc
(gen_sleigh.py).  A variant also serves closely related SM versions whose
encodings nvdisasm treats identically (e.g. SM86 also covers SM87).

ELF e_flags carry the SM number in bits 0-7 (CUDA <= 12, ELF ABI version 7) or
in bits 8-15 (CUDA 13, ABI version 8); the opinion matches either layout.
"""
import os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
LANG = os.path.join(HERE, '..', 'data', 'languages')

VARIANTS = [
    # variant, description, SM numbers mapped to it
    ('SM35', 'Kepler (sm_35, sm_37), 64-bit encoding', [35, 37]),
    ('SM52', 'Maxwell (sm_50, sm_52, sm_53), 64-bit encoding', [50, 52, 53]),
    ('SM60', 'Pascal (sm_60, sm_61, sm_62), 64-bit encoding', [60, 61, 62]),
    ('SM70', 'Volta (sm_70, sm_72)', [70, 72]),
    ('SM75', 'Turing (sm_75)', [75]),
    ('SM80', 'Ampere GA100 (sm_80)', [80]),
    ('SM86', 'Ampere GA10x / Orin (sm_86, sm_87)', [86, 87, 88]),
    ('SM89', 'Ada Lovelace (sm_89)', [89]),
    ('SM90', 'Hopper (sm_90, sm_90a)', [90]),
    ('SM100', 'Blackwell datacenter (sm_100, sm_101, sm_103, sm_110)', [100, 101, 103, 110]),
    ('SM120', 'Blackwell consumer (sm_120, sm_121)', [120, 121]),
]

def main(present):
    ld = ['<?xml version="1.0" encoding="UTF-8"?>', '<language_definitions>']
    op = ['<?xml version="1.0" encoding="UTF-8"?>', '<opinions>',
          '  <!-- e_machine 190 = EM_CUDA; secondary = e_flags with the SM number in bits 0-7',
          '       (CUDA <= 12) or bits 8-15 (CUDA 13). -->',
          '  <constraint loader="Executable and Linking Format (ELF)" compilerSpecID="default">']
    for v, desc, sms in VARIANTS:
        if v not in present:
            continue
        ld += ['  <language processor="SASS" endian="little" size="64" variant="%s" version="1.0"' % v,
               '            slafile="sass_%s.sla" processorspec="sass.pspec" id="SASS:LE:64:%s">' % (v, v),
               '    <description>NVIDIA SASS %s</description>' % desc,
               '    <compiler name="default" spec="sass.cspec" id="default"/>',
               '    <external_name tool="gnu" name="cuda"/>',
               '  </language>']
        for sm in sms:
            b = format(sm, '08b')
            op.append('    <constraint primary="190" secondary="0b%s%s" processor="SASS" endian="little" size="64" variant="%s"/> <!-- sm_%d, CUDA <= 12 -->' % ('.' * 24, b, v, sm))
            op.append('    <constraint primary="190" secondary="0b%s%s%s" processor="SASS" endian="little" size="64" variant="%s"/> <!-- sm_%d, CUDA 13 -->' % ('.' * 16, b, '.' * 8, v, sm))
        base = 'sass64.sinc' if v in ('SM35', 'SM52', 'SM60') else 'sass128.sinc'
        open(os.path.join(LANG, 'sass_%s.slaspec' % v), 'w').write(
            '# NVIDIA SASS %s.\n# The instruction file is generated by tools/gen_sleigh.py from spec/%s.json.gz.\n'
            '@include "%s"\n@include "sass_%s.sinc"\n' % (desc, v, base, v))
    ld.append('</language_definitions>')
    op += ['  </constraint>', '</opinions>']
    open(os.path.join(LANG, 'sass.ldefs'), 'w').write('\n'.join(ld) + '\n')
    open(os.path.join(LANG, 'sass.opinion'), 'w').write('\n'.join(op) + '\n')

if __name__ == '__main__':
    present = sys.argv[1:] or [v for v, _, _ in VARIANTS if os.path.exists(os.path.join(LANG, 'sass_%s.sinc' % v))]
    main(present)
    print('variants:', present)
