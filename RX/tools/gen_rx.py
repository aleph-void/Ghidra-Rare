#!/usr/bin/env python3
"""Generate the Renesas RX SLEIGH constructors.

    gen_rx.py tokens > data/languages/rx_tokens.sinc
    gen_rx.py        > data/languages/rx_gen.sinc

Encodings are transcribed from the "Instruction Code" chapter (section 4) of the Renesas RX Family
RXv3 Instruction Set Architecture User's Manual: Software (R01US0316EJ0100) and checked against
the RXv1 (R01US0032EJ0130) and RXv2 (R01US0071EJ0100) manuals for the version differences.
Operation and flag behavior come from section 3 of the same manuals.

Each instruction form is written as a list of opcode bytes, MSB first, using 0/1 for fixed bits
and letters for fields (S = Rs, D = Rd, T = Rs2, i = immediate bits, L = ld, M = mi, ...). The
generator turns runs of fixed bits into constraints on per-byte fields (n<k>_<hi><lo>), field
letters into per-byte operand fields (g<k>h = register in bits 7..4 of byte k, ...), and appends
displacement / immediate tokens. Constructors only valid from RXv2 or RXv3 on are wrapped in
"@if RXV >= n".
"""
import sys

OUT = []
NBYTES = 4   # opcode bytes that carry fields (dsp/imm follow as separate tokens)


def emit(s=""):
    OUT.append(s)


