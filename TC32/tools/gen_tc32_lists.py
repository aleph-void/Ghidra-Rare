#!/usr/bin/env python3
"""Generate TC32/data/languages/tc32_lists.sinc: the register-list operands of tpush, tpop,
treti, tstorem and tloadm.

One constructor per list value, so the display text matches the toolchain's
"{r0, r1, lr}" form exactly and the p-code is straight-line.

  python3 TC32/tools/gen_tc32_lists.py > TC32/data/languages/tc32_lists.sinc
"""

LO = ["r%d" % i for i in range(8)]


def regs(mask):
    return [LO[i] for i in range(8) if mask >> i & 1]


def text(names):
    return '"{' + ", ".join(names) + '}"'


def main():
    out = ["# Generated by TC32/tools/gen_tc32_lists.py; do not edit.", ""]

    # tpush {list}{, lr}: full descending stack, lowest register at the lowest address.
    for r in range(2):
        for m in range(256):
            names = regs(m) + (["lr"] if r else [])
            n = len(names)
            body = []
            if n:
                body.append("a:4 = sp - %d;" % (4 * n))
                for k, nm in enumerate(names):
                    body.append("*:4 (a + %d) = %s;" % (4 * k, nm))
                body.append("sp = a;")
            out.append("PushList: %s is rlist=%d & rbit=%d { %s }" % (text(names), m, r, " ".join(body)))
    out.append("")

    # tpop {list}{, pc} and treti {list}{, pc}: ascending loads; pc ends the list.
    for tab in ("PopList", "RetiList"):
        for r in range(2):
            for m in range(256):
                names = regs(m) + (["pc"] if r else [])
                n = len(names)
                body = []
                if n:
                    body.append("a:4 = sp;")
                    for k, nm in enumerate(regs(m)):
                        body.append("%s = *:4 (a + %d);" % (nm, 4 * k))
                    if r:
                        body.append("npc:4 = *:4 (a + %d);" % (4 * (n - 1)))
                    body.append("sp = a + %d;" % (4 * n))
                if tab == "RetiList":
                    body.append("unpackCPSR(SPSR);")
                if r:
                    body.append("pc = npc & 0xfffffffe;")
                    body.append("return [pc];")
                out.append("%s: %s is rlist=%d & rbit=%d { %s }" % (tab, text(names), m, r, " ".join(body)))
        out.append("")

    # tstorem rb!, {list}: ascending stores from rb, then rb += 4n.
    # tloadm rb!, {list}: rb += 4n first, then the loads, so a loaded rb wins.
    for m in range(256):
        names = regs(m)
        n = len(names)
        st = ["a:4 = rb8;"] + ["*:4 (a + %d) = %s;" % (4 * k, nm) for k, nm in enumerate(names)]
        st.append("rb8 = a + %d;" % (4 * n))
        ld = ["a:4 = rb8;", "rb8 = a + %d;" % (4 * n)]
        ld += ["%s = *:4 (a + %d);" % (nm, 4 * k) for k, nm in enumerate(names)]
        out.append("StmList: %s is rlist=%d & rb8 { %s }" % (text(names), m, " ".join(st)))
        out.append("LdmList: %s is rlist=%d & rb8 { %s }" % (text(names), m, " ".join(ld)))
    out.append("")
    print("\n".join(out))


if __name__ == "__main__":
    main()
