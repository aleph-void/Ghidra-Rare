#!/usr/bin/env python3
"""Generate data/languages/microblaze_fsl.sinc: the AXI4-Stream (FSL) get/put
instruction families (get/put and getd/putd with every n/c/t/a/e flag combination).

Encodings (UG984, Table 2-7):
  get/put   : 011011 rD rA  P N C T A E 000000 FSLx   (bits 15..10 = P N C T A E)
  getd/putd : 010011 rD rA  rB  P N C T A E 00000     (bits 10..5  = P N C T A E)
Mnemonic = [t][n][e][c][a] + get|put (+ 'd' for the dynamic forms).
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "data", "languages", "microblaze_fsl.sinc")


def name(p, n, c, t, a, e, dyn):
    s = ("t" if t else "") + ("n" if n else "") + ("e" if e else "") + \
        ("c" if c else "") + ("a" if a else "")
    return s + ("put" if p else "get") + ("d" if dyn else "")


lines = ["# Generated by scripts/gen_fsl.py -- do not edit by hand.",
         "# AXI4-Stream (FSL) get/put instructions, static (rfslN) and dynamic (rB) port forms.",
         ""]
for dyn in (0, 1):
    for v in range(64):
        p, n, c, t, a, e = [(v >> (5 - i)) & 1 for i in range(6)]
        mn = name(p, n, c, t, a, e, dyn)
        flags = v & 0x1f  # N C T A E
        if dyn:
            pat = "op=0x13 & dflags=%d" % v
            port = "RBP"
            if p:
                if t:
                    disp, regs = "RB", "& RB & RBP"
                else:
                    disp, regs = "RA, RB", "& RA & RB & RBP"
            else:
                disp, regs = "rd, RB", "& rd & RB & RBP"
        else:
            pat = "op=0x1b & sflags=%d" % v
            port = "fslnum"
            if p:
                if t:
                    disp, regs = "fslreg", "& fslreg & fslnum"
                else:
                    disp, regs = "RA, fslreg", "& RA & fslreg & fslnum"
            else:
                disp, regs = "rd, fslreg", "& rd & fslreg & fslnum"
        body = []
        if p:
            val = "0:4" if t else "RA"
            body.append("fslPut(%s:1, %s, %d:1);" % (port, val, flags))
        else:
            if t:  # test-only: status is updated, no data is transferred to rD
                body.append("fslGet(%s:1, %d:1);" % (port, flags))
            else:
                body.append("local v:4 = fslGet(%s:1, %d:1);" % (port, flags))
                body.append("W32(rd, v);")
        if n:
            body.append("C = fslStatus(%s:1, %d:1);" % (port, flags))
        lines.append(":%s %s is %s %s { %s }" % (mn, disp, pat, regs, " ".join(body)))
    lines.append("")

with open(OUT, "w") as f:
    f.write("\n".join(lines))
print("wrote", OUT)
