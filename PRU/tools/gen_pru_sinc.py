#!/usr/bin/env python3
"""Generate data/languages/pru.sinc for the TI PRU SLEIGH module.

The PRU ISA is small but very orthogonal: every ALU operand can be any
8/16/32-bit sub-field of any register, and the burst load/store and XFR
instructions move 1..124 bytes of the register file.  SLEIGH needs fixed
varnode sizes per constructor, so the repetitive parts are generated here.

Run:  python3 tools/gen_pru_sinc.py > data/languages/pru.sinc

Encodings follow TI SPRUIJ2 + the PRU-ICSS reference guide; operand syntax
follows GNU binutils (objdump -m pru) so the two can be diffed directly.
"""
import sys

REGN = ["r0", "r1", "sp", "ra", "fp"] + ["r%d" % i for i in range(5, 32)]
# selector -> (suffix, byte offset inside the 32-bit register, size)
SELS = [("b0", 0, 1), ("b1", 1, 1), ("b2", 2, 1), ("b3", 3, 1),
        ("w0", 0, 2), ("w1", 1, 2), ("w2", 2, 2), ("", 0, 4)]

out = []
w = out.append


def regname(r, sel):
    s = SELS[sel][0]
    return REGN[r] + ("." + s if s else "")


def emit_header():
    w("""# TI PRU / PRU-ICSS  -- generated by tools/gen_pru_sinc.py, do not edit by hand.
#
# Harvard machine: instruction memory ('code', 32-bit instruction words,
# 16-bit word PC) and data memory ('data', byte addressed, 32-bit).  The register
# file R0..R31 lives in the register space at byte offset 4*n so that the
# PRU's "register address" (&r2.b1 == 9) is the register-space offset; MVIx
# and the burst/XFR instructions use that to address the register file.
#
# Code addresses: the hardware PC counts 32-bit instruction words (16 bits,
# 64K words).  Ghidra's 'code' space is byte addressed (like the TI and GNU ELF
# files, objdump and dispru), so every instruction is 4-byte aligned and code
# address = 4 * hardware PC.  Values the program keeps in registers (the JAL
# link in ra.w2, LOOP_TOP/LOOP_END, register jump targets) are hardware word
# addresses: they are converted with "<< 2" / ">> 2" in the p-code.  PC is the
# Ghidra program counter (byte address).
#
# Feature switches (defined by the per-core-revision .slaspec files):
#   PRU_LMBD  LMBD                        (core rev >= V1)
#   PRU_XFR   XIN/XOUT/XCHG (+ZERO/FILL)  (>= V2)
#   PRU_MVI   MVIB/MVIW/MVID              (>= V2)
#   PRU_SXFR  SXIN/SXOUT/SXCHG            (>= V3)
#   PRU_LOOP  LOOP/ILOOP                  (>= V3)

define endian=little;
define alignment=4;

define space code     type=ram_space      size=3 wordsize=1 default;
define space data     type=ram_space      size=4 wordsize=1;
define space register type=register_space size=4;
""")
    # registers
    w("define register offset=0 size=4 [ %s ];" % " ".join(REGN))
    w("define register offset=0 size=1 [ %s ];" % " ".join(
        regname(r, s) for r in range(32) for s in range(4)))
    w("define register offset=0 size=2 [ %s ];" % " ".join(
        "%s %s" % (regname(r, 4), regname(r, 6)) for r in range(32)))
    w("define register offset=1 size=2 [ %s ];" % " ".join(
        "%s _" % regname(r, 5) for r in range(32)))
    w("""
# Constant table entries C0..C31 (LBCO/SBCO base addresses).  Most entries
# are fixed by the device, C24..C31 are partly programmable (CTBIR/CTPPR).
# Set their values with Set Register Value or ghidra_scripts/PRUSetConstantTable.py.
define register offset=0x100 size=4 [ %s ];
""" % " ".join("c%d" % i for i in range(32)))
    w("""define register offset=0x200 size=4 [ PC ];
define register offset=0x204 size=1 [ CARRY ];
# hardware loop state (LOOP/ILOOP)
define register offset=0x208 size=2 [ LOOP_CNT LOOP_TOP LOOP_END ];
define register offset=0x300 size=4 contextreg;

define context contextreg
  phase    = (0,0)
  loopend  = (1,1) noflow      # this instruction is the last one of a LOOP body
  looptop  = (2,17) noflow     # word address (byte/4) of the first instruction of the body
;

define token instr(32)
  op3     = (29,31)
  op2b    = (30,31)
  subop   = (25,28)
  io      = (24,24)
  rs2sel  = (21,23)
  rs2     = (16,20)
  imm8    = (16,23) dec
  imm16   = (8,23) dec
  rs1sel  = (13,15)
  rs1     = (8,12)
  rdsel   = (5,7)
  rd      = (0,4)
  rdb     = (5,6)
  cmp     = (27,29)
  brhi    = (25,26) signed
  brlo    = (0,7)
  bsbc    = (27,28)
  ls      = (28,28)
  bl64    = (25,27)
  bl31    = (13,15)
  bl0     = (7,7)
  cb      = (8,12)
  wake    = (23,23) dec
  xsub    = (23,24)
  xwba    = (15,22) dec
  xs      = (14,14)
  xlen    = (7,13)
  xlen_hi = (9,13)
  xlen_lo = (7,8)
  loopi   = (15,15)
  loopoff = (0,7)
  mvisz   = (16,17)
  mvires  = (18,20)
  mvisrc  = (21,22)
  mvidst  = (23,24)""")
    for f in ("rd", "rs1", "rs2"):
        lo = {"rd": 0, "rs1": 8, "rs2": 16}[f]
        for s in SELS:
            w("  %s_%s = (%d,%d)" % (f, s[0] or "d", lo, lo + 4))
    w("  cbr     = (8,12)")
    w(";\n")
    for s_i, s in enumerate(SELS):
        sfx = s[0] or "d"
        w("attach variables [ rd_%s rs1_%s rs2_%s ] [ %s ];" % (
            sfx, sfx, sfx, " ".join(regname(r, s_i) for r in range(32))))
    w("attach variables [ cbr ] [ %s ];" % " ".join("c%d" % i for i in range(32)))
    w("""
define pcodeop halt;
define pcodeop sleep;
define pcodeop xin;        # xin(device_id, byte_index) -> data from XFR bus
define pcodeop xout;       # xout(device_id, byte_index, data)
define pcodeop xchg;       # xchg(device_id, byte_index, data) -> data
define pcodeop sxin;
define pcodeop sxout;
define pcodeop sxchg;
define pcodeop mpy_xin;    # XIN from device 0 (MPY/MAC unit): mpy_xin(byte_index, r25 mode/status, r28, r29)
""")


def emit_operand_tables():
    # destination tables by size
    for size, sels in ((1, range(0, 4)), (2, range(4, 7)), (4, (7,))):
        for s in sels:
            sfx = SELS[s][0] or "d"
            w("D%d: rd_%s is rdsel=%d & rd_%s { export rd_%s; }" % (size, sfx, s, sfx, sfx))
    # zero-extended 32-bit source tables
    for f, fs in (("rs1", "S1"), ("rs2", "S2")):
        for s in range(8):
            sfx = SELS[s][0] or "d"
            if s == 7:
                w("%s: %s_d is %ssel=7 & %s_d { export %s_d; }" % (fs, f, f, f, f))
            else:
                w("%s: %s_%s is %ssel=%d & %s_%s { local t:4 = zext(%s_%s); export t; }" % (
                    fs, f, sfx, f, s, f, sfx, f, sfx))
    # native-size rs1 tables (LMBD needs the source width)
    for size, sels in ((1, range(0, 4)), (2, range(4, 7)), (4, (7,))):
        for s in sels:
            sfx = SELS[s][0] or "d"
            w("N%d: rs1_%s is rs1sel=%d & rs1_%s { export rs1_%s; }" % (size, sfx, s, sfx, sfx))
    w("""
OP2: S2    is io=0 & S2    { export S2; }
OP2: imm8  is io=1 & imm8  { export *[const]:4 imm8; }

# full 32-bit rs1 (LBBO/SBBO base register)
RB: rs1_d is rs1_d { export rs1_d; }
# byte register selected by rd + rdb (burst / XFR register-file start)
""")
    for s in range(4):
        w("BD: rd_b%d is rdb=%d & rd_b%d { export rd_b%d; }" % (s, s, s, s))
    w("""
# effective data address of a burst load/store
EA: is op3=7 & RB & OP2 { local a:4 = RB + OP2; export a; }
EA: is op3=4 & cbr & OP2 { local a:4 = cbr + OP2; export a; }

# code addresses (word addressed)
BRT: dest is brhi & brlo [ dest = inst_start + (((brhi << 8) | brlo) << 2); ] { export *[code]:4 dest; }
JT:  dest is io=1 & imm16 [ dest = imm16 << 2; ] { export *[code]:4 dest; }
""")


def chunks(n):
    off = 0
    while n > 0:
        c = 4 if n >= 4 else (2 if n >= 2 else 1)
        yield off, c
        off += c
        n -= c


def emit_blocks():
    """Register-file block tables keyed by length.

    Each table displays the length operand and performs the transfer
    between register-file bytes [roff, roff+L) and its peer."""
    kinds = {
        # name: (length fields, statement template)
        "LDB": "burst", "STB": "burst",
        "XINB": "xfr", "XOUTB": "xfr", "XCHGB": "xfr",
        "SXINB": "xfr", "SXOUTB": "xfr", "SXCHGB": "xfr",
        "ZEROB": "xfr", "FILLB": "xfr",
        "MPYB": "xfr",
    }
    guards = {"XINB": "PRU_XFR", "XOUTB": "PRU_XFR", "XCHGB": "PRU_XFR",
              "ZEROB": "PRU_XFR", "FILLB": "PRU_XFR", "MPYB": "PRU_XFR",
              "SXINB": "PRU_SXFR", "SXOUTB": "PRU_SXFR", "SXCHGB": "PRU_SXFR"}

    def stmt(kind, size, r, k):
        if kind == "LDB":
            return "%s = *[data]:%d (EA + %d);" % (r, size, k)
        if kind == "STB":
            return "*[data]:%d (EA + %d) = %s;" % (size, k, r)
        if kind == "ZEROB":
            return "%s = 0;" % r
        if kind == "FILLB":
            return "%s = 0x%s;" % (r, "ff" * size)
        if kind == "MPYB":
            return "%s = mpy_xin(%d:1, r25, r28, r29);" % (r, k)
        op = kind[:-1].lower()
        if op in ("xin", "sxin"):
            return "%s = %s(xwba:1, %d:1);" % (r, op, k)
        if op in ("xout", "sxout"):
            return "%s(xwba:1, %d:1, %s);" % (op, k, r)
        return "%s = %s(xwba:1, %d:1, %s);" % (r, op, k, r)

    def dyn_stmt(kind):
        # byte-by-byte variant for a run-time length taken from r0.bN
        r = "*[register]:1 p"
        if kind == "LDB":
            return "%s = *[data]:1 (EA + zext(i));" % r
        if kind == "STB":
            return "*[data]:1 (EA + zext(i)) = %s;" % r
        if kind == "ZEROB":
            return "%s = 0;" % r
        if kind == "FILLB":
            return "%s = 0xff;" % r
        if kind == "MPYB":
            return "%s = mpy_xin(i, r25, r28, r29);" % r
        op = kind[:-1].lower()
        if op in ("xin", "sxin"):
            return "%s = %s(xwba:1, i);" % (r, op)
        if op in ("xout", "sxout"):
            return "%s(xwba:1, i, %s);" % (op, r)
        return "%s = %s(xwba:1, i, %s);" % (r, op, r)

    # register-file window tables: RF<k>_<size> is the <size>-byte register
    # varnode at register-file byte offset (rd*4 + rdb + k)
    need = set()
    for L in range(1, 125):
        for k, size in chunks(L):
            need.add((k, size))
    for k, size in sorted(need):
        w("RF%d_%d: o is rd & rdb [ o = (rd << 2) + rdb + %d; ] { export *[register]:%d o; }" % (
            k, size, k, size))
    w("")

    for kind, lk in kinds.items():
        g = guards.get(kind)
        if g:
            w("@ifdef %s" % g)
        for v in range(128):
            if lk == "burst":
                cons = "bl64=%d & bl31=%d & bl0=%d" % (v >> 4, (v >> 1) & 7, v & 1)
            else:
                cons = "xlen=%d" % v
            if v < 124:
                L = v + 1
                body = []
                ops = []
                for k, size in chunks(L):
                    name = "RF%d_%d" % (k, size)
                    ops.append(name)
                    body.append(stmt(kind, size, name, k))
                extra = " & EA" if lk == "burst" else " & xwba"
                w("%s: %d is %s%s & %s { %s }" % (
                    kind, L, cons, extra, " & ".join(ops), " ".join(body)))
            else:
                b = v - 124
                extra = " & EA" if lk == "burst" else " & xwba"
                w("%s: \"r0.b%d\" is %s & rd & rdb%s {\n"
                  "  local i:1 = 0;\n"
                  "  <top>\n"
                  "  if (i >= r0.b%d) goto <done>;\n"
                  "  local p:4 = (rd << 2) + rdb + zext(i);\n"
                  "  %s\n"
                  "  i = i + 1;\n"
                  "  goto <top>;\n"
                  "  <done>\n"
                  "}" % (kind, b, cons, extra, b, dyn_stmt(kind)))
        if g:
            w("@endif")
        w("")


ALU = [
    # subop, mnemonic, kind
    (0, "add", "add"), (1, "adc", "adc"), (2, "sub", "sub"), (3, "suc", "suc"),
    (4, "lsl", "lsl"), (5, "lsr", "lsr"), (6, "rsb", "rsb"), (7, "rsc", "rsc"),
    (8, "and", "and"), (9, "or", "or"), (10, "xor", "xor"), (11, "not", "not"),
    (12, "min", "min"), (13, "max", "max"), (14, "clr", "clr"), (15, "set", "set"),
]


def alu_body(kind, size, a="S1", b="OP2", d=None):
    d = d or "D%d" % size
    bits = size * 8

    def carry(expr):
        return ("local t:8 = %s; %s = t:%d; CARRY = t[%d,1];" % (expr, d, size, bits))

    def res(expr):
        if size == 4:
            return "%s = %s;" % (d, expr)
        return "local r:4 = %s; %s = r:%d;" % (expr, d, size)

    if kind == "add":
        return carry("zext(%s) + zext(%s)" % (a, b))
    if kind == "adc":
        return carry("zext(%s) + zext(%s) + zext(CARRY)" % (a, b))
    if kind == "sub":
        return carry("zext(%s) - zext(%s)" % (a, b))
    if kind == "suc":
        return carry("zext(%s) - zext(%s) - zext(CARRY)" % (a, b))
    if kind == "rsb":
        return carry("zext(%s) - zext(%s)" % (b, a))
    if kind == "rsc":
        return carry("zext(%s) - zext(%s) - zext(CARRY)" % (b, a))
    if kind == "lsl":
        return res("%s << (%s & 0x1f)" % (a, b))
    if kind == "lsr":
        return res("%s >> (%s & 0x1f)" % (a, b))
    if kind == "and":
        return res("%s & %s" % (a, b))
    if kind == "or":
        return res("%s | %s" % (a, b))
    if kind == "xor":
        return res("%s ^ %s" % (a, b))
    if kind == "not":
        return res("~%s" % a)
    if kind == "min":
        return res("(zext(%s < %s) * %s) + (zext(%s >= %s) * %s)" % (b, a, b, b, a, a))
    if kind == "max":
        return res("(zext(%s > %s) * %s) + (zext(%s <= %s) * %s)" % (b, a, b, b, a, a))
    if kind == "clr":
        return res("%s & ~(1 << (%s & 0x1f))" % (a, b))
    if kind == "set":
        return res("%s | (1 << (%s & 0x1f))" % (a, b))
    raise KeyError(kind)


def emit_instructions():
    w("""
# ---------------------------------------------------------------------------
# top level: hardware-loop bookkeeping
# ---------------------------------------------------------------------------
LTOP: dest is looptop [ dest = looptop << 2; ] { export *[code]:4 dest; }

:^instruction is phase=0 & loopend=0 & instruction [ phase=1; ] { build instruction; }
:^instruction is phase=0 & loopend=1 & instruction & LTOP [ phase=1; ] {
  build instruction;
  LOOP_CNT = LOOP_CNT - 1;
  if (LOOP_CNT != 0) goto LTOP;
}

with : phase=1 {
""")
    # ---- format 1 ALU
    w("# ---- Format 1: arithmetic / logic")
    for sub, mn, kind in ALU:
        for size in (1, 2, 4):
            dc = {1: "rdsel<4", 2: "rdsel>3 & rdsel<7", 4: "rdsel=7"}[size]
            if kind == "not":
                # TI clpru encodes NOT with IO=0 and rs2=r0.b0; binutils only decodes IO=1.
                w(":%s D%d, S1 is op3=0 & subop=%d & %s & D%d & S1 { %s }" % (
                    mn, size, sub, dc, size, alu_body(kind, size)))
            else:
                w(":%s D%d, S1, OP2 is op3=0 & subop=%d & %s & D%d & S1 & OP2 { %s }" % (
                    mn, size, sub, dc, size, alu_body(kind, size)))
    w("# pseudo ops (binutils): nop = or r0, r0, r0 ; mov = or d, s, 0")
    w(":nop is op3=0 & subop=9 & io=0 & rs2sel=7 & rs2=0 & rs1sel=7 & rs1=0 & rdsel=7 & rd=0 { }")
    for size in (1, 2, 4):
        dc = {1: "rdsel<4", 2: "rdsel>3 & rdsel<7", 4: "rdsel=7"}[size]
        body = "D4 = S1;" if size == 4 else "D%d = S1:%d;" % (size, size)
        w(":mov D%d, S1 is op3=0 & subop=9 & io=1 & imm8=0 & %s & D%d & S1 { %s }" % (
            size, dc, size, body))

    # ---- format 2
    w("""
# ---- Format 2: jumps, LDI, LMBD, HALT, SLP, XFR, LOOP, MVI
:jmp JT     is op3=1 & subop=0 & JT     { goto JT; }
:jmp S2     is op3=1 & subop=0 & io=0 & S2 { local w:2 = S2:2; local t:3 = zext(w) << 2; goto [t]; }
:ret        is op3=1 & subop=0 & io=0 & rs2sel=6 & rs2=3 { local t:3 = zext(ra.w2) << 2; return [t]; }
""")
    for size in (1, 2, 4):
        dc = {1: "rdsel<4", 2: "rdsel>3 & rdsel<7", 4: "rdsel=7"}[size]
        link = "D%d = inst_next;" % size if size != 4 else "local l:2 = inst_next >> 2; D4 = zext(l);"
        if size == 1:
            link = "local l:2 = inst_next >> 2; D1 = l:1;"
        if size == 2:
            link = "D2 = inst_next >> 2;"
        w(":jal D%d, JT is op3=1 & subop=1 & %s & D%d & JT { %s call JT; }" % (
            size, dc, size, link))
        w(":jal D%d, S2 is op3=1 & subop=1 & io=0 & %s & D%d & S2 { local w:2 = S2:2; local t:3 = zext(w) << 2; %s call [t]; }" % (
            size, dc, size, link))
    w(":call JT is op3=1 & subop=1 & rdsel=6 & rd=3 & JT { ra.w2 = inst_next >> 2; call JT; }")
    w(":call S2 is op3=1 & subop=1 & io=0 & rdsel=6 & rd=3 & S2 { local w:2 = S2:2; local t:3 = zext(w) << 2; ra.w2 = inst_next >> 2; call [t]; }")
    for size in (1, 2, 4):
        dc = {1: "rdsel<4", 2: "rdsel>3 & rdsel<7", 4: "rdsel=7"}[size]
        body = {1: "local v:2 = imm16; D1 = v:1;", 2: "D2 = imm16;", 4: "D4 = imm16;"}[size]
        w(":ldi D%d, imm16 is op3=1 & subop=2 & %s & D%d & imm16 { %s }" % (size, dc, size, body))
    w("@ifdef PRU_LMBD")
    for dsz in (1, 2, 4):
        dc = {1: "rdsel<4", 2: "rdsel>3 & rdsel<7", 4: "rdsel=7"}[dsz]
        for ssz in (1, 2, 4):
            sc = {1: "rs1sel<4", 2: "rs1sel>3 & rs1sel<7", 4: "rs1sel=7"}[ssz]
            bits = ssz * 8
            trunc = "OP2" if ssz == 4 else "OP2:%d" % ssz
            body = ("local m:%d = (%s & 1) ^ 1; local x:%d = N%d ^ (m * 0x%s); "
                    "local n:4 = lzcount(x); "
                    "local r:4 = (zext(x != 0) * (%d - n)) + (zext(x == 0) * 32); " % (
                        ssz, trunc, ssz, ssz, "ff" * ssz, bits - 1))
            body += ("D4 = r;" if dsz == 4 else "D%d = r:%d;" % (dsz, dsz))
            w(":lmbd D%d, N%d, OP2 is op3=1 & subop=3 & %s & %s & D%d & N%d & OP2 { %s }" % (
                dsz, ssz, dc, sc, dsz, ssz, body))
    w("@endif")
    w(""":halt is op3=1 & subop=5 { halt(); goto inst_start; }
:slp wake is op3=1 & subop=15 & wake { sleep(wake:1); }
""")
    # XFR
    xfr = [(1, 0, "xin", "XINB", "PRU_XFR"), (2, 0, "xout", "XOUTB", "PRU_XFR"),
           (3, 0, "xchg", "XCHGB", "PRU_XFR"), (1, 1, "sxin", "SXINB", "PRU_SXFR"),
           (2, 1, "sxout", "SXOUTB", "PRU_SXFR"), (3, 1, "sxchg", "SXCHGB", "PRU_SXFR")]
    for xsub, s, mn, tbl, g in xfr:
        w("@ifdef %s" % g)
        w(":%s xwba, BD, %s is op3=1 & subop=7 & xsub=%d & xs=%d & xwba & BD & %s { build %s; }" % (
            mn, tbl, xsub, s, tbl, tbl))
        if mn == "xin":
            w(":xin \"0\", BD, MPYB is op3=1 & subop=7 & xsub=1 & xs=0 & xwba=0 & BD & MPYB { build MPYB; }")
            w(":fill BD, FILLB is op3=1 & subop=7 & xsub=1 & xs=0 & xwba=254 & BD & FILLB { build FILLB; }")
            w(":zero BD, ZEROB is op3=1 & subop=7 & xsub=1 & xs=0 & xwba=255 & BD & ZEROB { build ZEROB; }")
        w("@endif")
    # LOOP
    w("""@ifdef PRU_LOOP
LCNT: imm is io=1 & imm8 [ imm = imm8 + 1; ] { export *[const]:2 imm; }
LCNT: S2 is io=0 & S2 { local c:2 = S2:2; export c; }
LEND: dest is loopoff [ dest = inst_start + (loopoff << 2); ] { export *[code]:4 dest; }
LLAST: dest is loopoff [ dest = inst_start + ((loopoff - 1) << 2); ] { export *[code]:4 dest; }
""")
    for i, mn in ((0, "loop"), (1, "iloop")):
        w(":%s LEND, LCNT is op3=1 & subop=8 & loopi=%d & loopoff>1 & LEND & LLAST & LCNT "
          "[ loopend=1; looptop=(inst_start >> 2) + 1; globalset(LLAST, loopend); globalset(LLAST, looptop); ] "
          "{ LOOP_CNT = LCNT; LOOP_TOP = inst_next >> 2; LOOP_END = &LEND >> 2; if (LOOP_CNT == 0) goto LEND; }" % (mn, i))
        w(":%s LEND, LCNT is op3=1 & subop=8 & loopi=%d & loopoff<2 & LEND & LCNT "
          "{ LOOP_CNT = LCNT; LOOP_TOP = inst_next >> 2; LOOP_END = &LEND >> 2; if (LOOP_CNT == 0) goto LEND; }" % (mn, i))
    w("@endif")

    # MVI
    w("\n@ifdef PRU_MVI")
    # pointer registers (byte fields; the hardware restricts them to r1.b0..b3)
    for s in range(4):
        w("PD: rd_b%d is rdsel=%d & rd=1 & rd_b%d { export rd_b%d; }" % (s, s, s, s))
        w("PS: rs1_b%d is rs1sel=%d & rs1=1 & rs1_b%d { export rs1_b%d; }" % (s, s, s, s))
    for sz, szn in ((1, "b"), (2, "w"), (4, "d")):
        code = {1: 0, 2: 1, 4: 2}[sz]
        t = "MS%d" % sz
        # source operand exporting an sz-byte value
        conv = "S1" if sz == 4 else "S1:%d" % sz
        w("%s: S1     is mvisrc=0 & S1 { local v:%d = %s; export v; }" % (t, sz, conv))
        w("%s: \"*\"^PS     is mvisrc=1 & PS { local pp:4 = zext(PS); local v:%d = *[register]:%d pp; export v; }" % (t, sz, sz))
        w("%s: \"*\"^PS^\"++\" is mvisrc=2 & PS { local pp:4 = zext(PS); local v:%d = *[register]:%d pp; PS = PS + %d; export v; }" % (t, sz, sz, sz))
        w("%s: \"*--\"^PS   is mvisrc=3 & PS { PS = PS - %d; local pp:4 = zext(PS); local v:%d = *[register]:%d pp; export v; }" % (t, sz, sz, sz))
        base = "op3=1 & subop=6 & mvires=0 & mvisz=%d" % code
        mn = "mvi" + szn
        # direct destination (source must be indirect)
        for dsz in (1, 2, 4):
            dc = {1: "rdsel<4", 2: "rdsel>3 & rdsel<7", 4: "rdsel=7"}[dsz]
            if dsz == sz:
                body = "D%d = %s;" % (dsz, t)
            elif dsz > sz:
                body = "D%d = zext(%s);" % (dsz, t)
            else:
                body = "D%d = %s:%d;" % (dsz, t, dsz)
            w(":%s D%d, %s is %s & mvidst=0 & mvisrc!=0 & %s & D%d & %s { %s }" % (
                mn, dsz, t, base, dc, dsz, t, body))
        w(":%s \"*\"^PD, %s is %s & mvidst=1 & PD & %s { local v:%d = %s; local pp:4 = zext(PD); *[register]:%d pp = v; }" % (
            mn, t, base, t, sz, t, sz))
        w(":%s \"*\"^PD^\"++\", %s is %s & mvidst=2 & PD & %s { local v:%d = %s; local pp:4 = zext(PD); *[register]:%d pp = v; PD = PD + %d; }" % (
            mn, t, base, t, sz, t, sz, sz))
        w(":%s \"*--\"^PD, %s is %s & mvidst=3 & PD & %s { local v:%d = %s; PD = PD - %d; local pp:4 = zext(PD); *[register]:%d pp = v; }" % (
            mn, t, base, t, sz, t, sz, sz))
    w("@endif")

    # ---- format 4: quick branches with compare
    w("\n# ---- Format 4: QBxx (branch if OP(255) <cond> REG1)")
    for c, mn, cond in ((4, "qbgt", ">"), (6, "qbge", ">="), (1, "qblt", "<"),
                        (3, "qble", "<="), (2, "qbeq", "=="), (5, "qbne", "!=")):
        w(":%s BRT, S1, OP2 is op2b=1 & cmp=%d & BRT & S1 & OP2 { if (OP2 %s S1) goto BRT; }" % (
            mn, c, cond))
    w(":qba BRT is op2b=1 & cmp=7 & BRT { goto BRT; }")

    # ---- format 5: bit test branches
    w("\n# ---- Format 5: QBBS / QBBC (+ WBS / WBC pseudo ops)")
    w(":qbbs BRT, S1, OP2 is op3=6 & bsbc=2 & BRT & S1 & OP2 { if (((S1 >> (OP2 & 0x1f)) & 1) != 0) goto BRT; }")
    w(":qbbc BRT, S1, OP2 is op3=6 & bsbc=1 & BRT & S1 & OP2 { if (((S1 >> (OP2 & 0x1f)) & 1) == 0) goto BRT; }")
    w(":wbc S1, OP2 is op3=6 & bsbc=2 & brhi=0 & brlo=0 & S1 & OP2 { if (((S1 >> (OP2 & 0x1f)) & 1) != 0) goto inst_start; }")
    w(":wbs S1, OP2 is op3=6 & bsbc=1 & brhi=0 & brlo=0 & S1 & OP2 { if (((S1 >> (OP2 & 0x1f)) & 1) == 0) goto inst_start; }")

    # ---- format 6: burst load/store
    w("""
# ---- Format 6: LBBO/SBBO (register base) and LBCO/SBCO (constant table base)
:lbbo BD, RB, OP2, LDB is op3=7 & ls=1 & BD & RB & OP2 & LDB { build LDB; }
:sbbo BD, RB, OP2, STB is op3=7 & ls=0 & BD & RB & OP2 & STB { build STB; }
:lbco BD, cbr, OP2, LDB is op3=4 & ls=1 & BD & cbr & OP2 & LDB { build LDB; }
:sbco BD, cbr, OP2, STB is op3=4 & ls=0 & BD & cbr & OP2 & STB { build STB; }

} # with phase=1
""")


emit_header()
emit_operand_tables()
emit_blocks()
emit_instructions()
