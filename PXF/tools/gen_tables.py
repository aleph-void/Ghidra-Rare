#!/usr/bin/env python3
"""Generate the PXF SLEIGH include files that are tedious to write by hand.

    python3 PXF/tools/gen_tables.py > PXF/data/languages/pxf_tables.sinc
    python3 PXF/tools/gen_tables.py branches > PXF/data/languages/pxf_branches.sinc
"""
import sys
# M-unit operation table: index = H[29:27] + 8 * ext, where ext = L[7:6] when L[9:8] == 0,
# otherwise 0.  (name, has width suffix, has mode suffix); None = undefined encoding.
MOPS = [
    ("or", 1, 1), ("shift", 1, 1), ("xor", 1, 1), ("and", 1, 1),
    ("addu", 1, 1), ("subu", 1, 1), ("adduc", 1, 1), ("addup1", 1, 1),
    ("nor", 1, 1), ("nshift", 1, 1), ("nxor", 1, 1), ("nand", 1, 1),
    ("cntzl", 1, 0), ("cntzm", 1, 0), ("bswap", 1, 0), ("eswap", 1, 0),
    ("multu", 1, 1), ("divu", 0, 1), ("mcks", 0, 0), ("eadd", 0, 0),
    None, None, None, None,
    ("aor", 0, 1), ("aswap", 0, 1), ("enque", 0, 0), ("deque", 0, 0),
    ("aaddu", 0, 1), ("asubu", 0, 1), ("amfadd", 0, 1), ("dread", 0, 0),
]
EXT = ["(l9_8!=0 | l7_6=0)", "(l9_8=0 & l7_6=1)", "(l9_8=0 & l7_6=2)", "(l9_8=0 & l7_6=3)"]

out = ["# Generated by PXF/tools/gen_tables.py; do not edit.", ""]
for i, m in enumerate(MOPS):
    if m is None:
        continue
    name, w, md = m
    disp = '"m' + name + '"'
    if w or md:
        disp += '^"."'
        if w:
            disp += "^hw"
        if md:
            disp += "^hmode"
    pat = f"hop={i % 8} & {EXT[i // 8]}" + (" & hw" if w else "") + (" & hmode" if md else "")
    out.append(f"malu: {disp} is {pat} {{}}")
out.append("")
# xdma count: decimal (H[21:18] << 4) + H[7:4]; SLEIGH prints computed values in hex only.
for v in range(256):
    out.append(f'xdmacnt: "{v}" is h21_18={v >> 4} & h7_4={v & 15} {{}}')
if len(sys.argv) == 1:
    print("\n".join(out))


# ---- branches: pxf_branches.sinc ----
# Flow model (see README): branches take effect immediately. The hardware has one branch delay
# slot (cancelled on a taken branch by the "cdsbt" micro-op), but real microcode puts branches in
# delay slots, which Ghidra cannot represent, so delay slots are not modelled. cr_zero reads as
# 0 (it only ever appears with the branch-if-false forms), so bcf/balcf on cr_zero always branch.
def body(cond, jump, always):
    if always:
        return jump
    if jump.startswith("goto ") and "[" not in jump:
        return f"if {cond} {jump}"
    return f"if (!{cond}) goto inst_next; {jump}"


def branches():
    out = ["# Generated by PXF/tools/gen_tables.py; do not edit.", ""]
    # M unit compare and branch: bne balne beq baleq
    for op, (eq, call) in enumerate([(0, 0), (0, 1), (1, 0), (1, 1)]):
        cond = f"(hB_dc4 {'==' if eq else '!='} hC_dc4)"
        jump = "call mtarget;" if call else "goto mtarget;"
        out.append(f'mops: hB_dc4^", "^hC_dc4^", "^mtarget is hfmt=0 & hcls=3 & hcb={op} & '
                   f'hB_dc4 & hC_dc4 & mtarget {{ {body(cond, jump, False)} }}')
    out.append("")
    # S unit: bcf balcf bct balct, relative (L[31:30] = 3) and register (L[31:30] = 2)
    for form in ("rel", "reg"):
        for op, (true, call) in enumerate([(0, 0), (0, 1), (1, 0), (1, 1)]):
            cond = "(lcond != 0)" if true else "(lcond == 0)"
            for crz in ((False, True) if not true else (False,)):
                for lr in ((False, True) if form == "reg" and not call else (False,)):
                    if form == "rel":
                        pat, disp, ops = "lfmt=3 & l27=0", 'lcond^", "^starget', "lcond & starget"
                        jump = "call starget;" if call else "goto starget;"
                    else:
                        pat, disp, ops = "lfmt=2 & l27=0", 'lcond^", "^lT_bc4', "lcond & lT_bc4"
                        jump = ("call [lT_bc4];" if call else
                                "return [lT_bc4];" if lr else "goto [lT_bc4];")
                    pat += f" & l29_28={op}"
                    if crz:
                        pat += " & lc=0"
                    if lr:
                        pat += " & lT_dc4=14"
                    out.append(f"sops: {disp} is {pat} & {ops} {{ {body(cond, jump, crz)} }}")
    return "\n".join(out)


if __name__ == "__main__" and len(sys.argv) > 1 and sys.argv[1] == "branches":
    print(branches())
