#!/usr/bin/env python3
"""Generate data/languages/sh4aldsp_pops.sinc: the SH4AL-DSP 32-bit DSP operation instructions
(prefix 111110 + A field, then the B field).

    tools/gen_pops.py > data/languages/sh4aldsp_pops.sinc

Encodings: SH4AL-DSP Software Manual (REJ09B0002-0150) tables 3.17-3.26 and 6.39.  Operation:
section 6.5 and the operation descriptions of section 11.4.  MIT License.
"""
import re

HEADER = r"""# GENERATED by tools/gen_pops.py - do not edit.  MIT License, see sh4aldsp.sinc.
#
# SH4AL-DSP DSP operation instructions (32 bits: 111110 + A field, B field).  The B-field operation
# reads its sources and computes, the A field (parallel MOVX/MOVY, sh4aldsp_xy.sinc) runs, then the
# operation's results are written.  DCT/DCF operations run when DSR.DC is 1/0 and never change DSR
# or T; the A field runs regardless.  Unconditional operations update DC (selected by DSR.CS),
# N, Z, V, GT, the T bit (DSR.TC/TS) and the accumulating AN, AZ, AV, AGT bits (DSR[11:8] != 0).
#
# Operands are attached registers (sh4aldsp.sinc): Sx = X0 X1 A0 A1, Sy = Y0 Y1 M0 M1,
# Dz = A1 (5) A0 (7) X0 X1 Y0 Y1 M0 (C) M1 (E), Du = X0 Y0 A0 A1, Dg = M0 M1 A0 A1,
# Se = X0 X1 Y0 A1, Sf = Y0 Y1 X0 A1.  The *g_r fields name the guard register of an A operand
# (NOG, a scratch byte, for the others); A operands are 40-bit, the others are sign-extended.

define pcodeop pwad;
define pcodeop pwsb;

PSIMM: "#"^b_imm7 is b_imm7 { export *[const]:1 b_imm7; }
"""

# condition field values: unconditional encoding depends on the instruction group
COND = {"": None, "dct": 2, "dcf": 3}


def fixed_tail(res="res", cb="cb", orng="orng", flags="dsp_arith_flags"):
    """overflow detection, protection and flags for a fixed-point result"""
    return [
        f"local ov:1 = sext({res}:4) != {res};",
        f"local ovav:1 = ov | {orng};",
        f"dsp_saturate({res}, ovav);",
        "ov = ov & (S == 0);",
        f"{orng} = {orng} & (S == 0);",
    ], [f"{flags}({res}, {cb}, ov, {orng}, ovav);"]


def op_body(kind, a, b):
    c, f = _op_body(kind, a, b)
    if isinstance(f, tuple):
        return c + f[0], f[1]
    return c, f


def _op_body(kind, a, b):
    """p-code computing local res:5 (and cb/orng) for an ALU kind; returns (compute, flags)"""
    if kind in ("add", "addc"):
        c = ["local a:5 = %s;" % a, "local b:5 = %s;" % b]
        if kind == "add":
            c += ["local res:5 = a + b;", "local cb:1 = carry(a:4, b:4);", "local orng:1 = scarry(a, b);"]
        else:
            c += ["local ci:4 = zext(DC);", "local s32:4 = a:4 + b:4;",
                  "local res:5 = a + b + zext(DC);",
                  "local cb:1 = carry(a:4, b:4) || carry(s32, ci);",
                  "local orng:1 = ((a s< 0) == (b s< 0)) && ((res s< 0) != (a s< 0));"]
        return c, fixed_tail(flags="dsp_carry_flags" if kind == "addc" else "dsp_arith_flags")
    if kind in ("sub", "subc"):
        c = ["local a:5 = %s;" % a, "local b:5 = %s;" % b]
        if kind == "sub":
            c += ["local res:5 = a - b;", "local cb:1 = a:4 < b:4;", "local orng:1 = sborrow(a, b);"]
        else:
            c += ["local ci:4 = zext(DC);", "local d32:4 = a:4 - b:4;",
                  "local res:5 = a - b - zext(DC);",
                  "local cb:1 = (a:4 < b:4) || (d32 < ci);",
                  "local orng:1 = ((a s< 0) != (b s< 0)) && ((res s< 0) != (a s< 0));"]
        return c, fixed_tail(flags="dsp_carry_flags" if kind == "subc" else "dsp_arith_flags")
    if kind == "copy":
        return ["local a:5 = %s;" % a, "local res:5 = a;", "local cb:1 = 0;", "local orng:1 = 0;"], fixed_tail()
    if kind == "neg":
        return ["local a:5 = %s;" % a, "local res:5 = 0 - a;", "local cb:1 = a:4 != 0;",
                "local orng:1 = (a s< 0) && (res s< 0);"], fixed_tail()
    if kind == "abs":
        return ["local a:5 = %s;" % a, "local isneg:1 = a s< 0;",
                "local res:5 = a + zext(isneg) * (0 - a - a);",
                "local cb:1 = isneg && (a:4 != 0);",
                "local orng:1 = isneg && (res s< 0);"], fixed_tail()
    if kind == "rnd":
        return ["local a:5 = %s;" % a, "local res:5 = (a + 0x8000) & 0xffffff0000;",
                "local cb:1 = carry(a:4, 0x8000:4);", "local orng:1 = scarry(a, 0x8000:5);"], fixed_tail()
    if kind in ("inc", "dec"):
        c = ["local a:5 = %s & 0xffffff0000;" % a]
        if kind == "inc":
            c += ["local res:5 = a + 0x10000;", "local cb:1 = carry(a:4, 0x10000:4);",
                  "local orng:1 = scarry(a, 0x10000:5);"]
        else:
            c += ["local res:5 = a - 0x10000;", "local cb:1 = a:4 < 0x10000;",
                  "local orng:1 = sborrow(a, 0x10000:5);"]
        pre, post = fixed_tail()
        # integer result: the saturated value keeps only its upper word (00 7FFF 0000 / FF 8000 0000)
        pre.insert(3, "res = res & 0xffffff0000;")
        return c, (pre, post)
    if kind == "clr":
        return ["local res:5 = 0;"], ["dsp_arith_flags(res, 0:1, 0:1, 0:1, 0:1);"]
    if kind == "dmsb":
        return ["local a:5 = %s;" % a, "local v:5 = a ^ (a s>> 39);", "local lz:2 = lzcount(v);",
                "local r16:2 = lz - 9;", "local res:5 = sext(r16) << 16;"], \
               ["dsp_arith_flags(res, 0:1, 0:1, 0:1, 0:1);"]
    if kind == "swap":
        return ["local a:5 = %s;" % a, "local w:4 = a:4;", "local res:5 = sext((w << 16) | (w >> 16));"], \
               ["dsp_arith_flags(res, 0:1, 0:1, 0:1, 0:1);"]
    if kind in ("and", "or", "xor"):
        o = {"and": "&", "or": "|", "xor": "^"}[kind]
        return ["local a:5 = %s;" % a, "local b:5 = %s;" % b,
                "local ash:5 = a >> 16;", "local bsh:5 = b >> 16;", "local hw:2 = ash:2 %s bsh:2;" % o, "local res:5 = zext(hw) << 16;"], \
               ["dsp_logic_flags(hw);"]
    raise ValueError(kind)


def psha(a, amount):
    """arithmetic shift of a 40-bit value; amount is a 1-byte signed count (-32..+32)"""
    c = ["local a:5 = %s;" % a, "local sh:1 = %s;" % amount, "local res:5 = 0;", "local cb:1 = 0;",
         "local t:8 = 0;", "local cnt:1 = 0;",
         "if (sh s< 0) goto <right>;",
         "t = sext(a) << sh;", "res = t:5;", "cb = t[32,1];", "goto <shdone>;",
         "<right>", "cnt = 0 - sh;", "res = a s>> cnt;", "t = zext(a) >> (cnt - 1);", "cb = t[0,1];",
         "<shdone>"]
    c += ["local ov:1 = sext(res:4) != res;", "local ovav:1 = ov;", "dsp_saturate(res, ovav);",
          "ov = ov & (S == 0);"]
    return c, ["dsp_shift_flags(res s< 0, res == 0, cb, ov, ovav);"]


def pshl(a, amount):
    """logical shift of the upper word; amount is a 1-byte signed count (-16..+16)"""
    c = ["local a:5 = %s;" % a, "local sh:1 = %s;" % amount, "local ash:5 = a >> 16;", "local hw:4 = zext(ash:2);",
         "local t:4 = 0;", "local cb:1 = 0;", "local cnt:1 = 0;",
         "if (sh s< 0) goto <right>;",
         "t = hw << sh;", "cb = t[16,1];", "goto <shdone>;",
         "<right>", "cnt = 0 - sh;", "t = hw >> cnt;", "local u:4 = hw >> (cnt - 1);", "cb = u[0,1];",
         "<shdone>", "local r16:2 = t:2;", "local res:5 = zext(r16) << 16;"]
    t = ["dsp_shift_flags(r16 s< 0, r16 == 0, cb, 0:1, 0:1);"]
    return c, t


def emit(lines, mnem, display, pattern, compute, flags, cond, write):
    """one constructor: compute reads the sources into locals, the A field runs, write commits"""
    if cond:
        disp = '"%s" "%s" %s AFP' % (cond, mnem, display) if display else '"%s" "%s" AFP' % (cond, mnem)
    else:
        disp = '"%s" %s AFP' % (mnem, display) if display else '"%s" AFP' % mnem
    body = []
    if cond == "dct":
        body.append("local doit:1 = DC != 0;")
    elif cond == "dcf":
        body.append("local doit:1 = DC == 0;")
    body += compute
    if not cond:
        body += flags
    body.append("build AFP;")
    if cond:
        body.append("if (doit == 0) goto <skip>;")
    body += write
    if cond:
        body.append("<skip>")
    disp = disp.replace("SX", "sx_r").replace("SY", "sy_r").replace("DZR", "dz_r").replace("DU", "du_r") \
        .replace("DG", "dg_r").replace("SE", "se_r").replace("SF", "sf_r")
    pattern = pattern.replace("SX", "sx_r & sxg_r & b_sx").replace("SY", "sy_r").replace("DZR & DZW", "dz_r & dzg_r & b_dz") \
        .replace("DZR", "dz_r & dzg_r & b_dz").replace("DU", "du_r & dug_r").replace("DG", "dg_r & dgg_r") \
        .replace("SE", "se_r").replace("SF", "sf_r")
    text = "\n".join(body)
    pre = []
    if re.search(r"\bSX\b", text):
        pre += ["local sxn:1 = b_sx;", "local sxa:1 = sxn > 1;",
                "local SX:5 = (zext(sxa) * ((zext(sxg_r) << 32) | zext(sx_r))) | (zext(sxa == 0) * sext(sx_r));"]
    if re.search(r"\bSY\b", text):
        pre += ["local SY:5 = sext(sy_r);"]
    if re.search(r"\bDZR\b", text):
        pre += ["local dzn:1 = b_dz;", "local dza:1 = (dzn == 5) || (dzn == 7);",
                "local DZR:5 = (zext(dza) * ((zext(dzg_r) << 32) | zext(dz_r))) | (zext(dza == 0) * sext(dz_r));"]
    if re.search(r"\bS[EF]\b", text):
        pre += ["local SE:2 = se_r(2);", "local SF:2 = sf_r(2);"]
    body = pre + body
    lines.append("INSN: %s is op6=0x3e & AFP ; %s {" % (disp, pattern))
    for b in body:
        lines.append(("" if b.startswith("<") else "\t") + b)
    lines.append("}")


def main():
    L = [HEADER]
    W = ["dz_r = res:4;", "dzg_r = res(4);"]

    # three-operand ALU (conditional group: cc 01 = unconditional, 10 DCT, 11 DCF)
    three = [(0b101100, "padd", "add", "SX,SY,DZR", "SX", "SY"),
             (0b101000, "psub", "sub", "SX,SY,DZR", "SX", "SY"),
             (0b100001, "psub", "subr", "SY,SX,DZR", "SY", "SX"),
             (0b100101, "pand", "and", "SX,SY,DZR", "SX", "SY"),
             (0b101101, "por", "or", "SX,SY,DZR", "SX", "SY"),
             (0b101001, "pxor", "xor", "SX,SY,DZR", "SX", "SY")]
    for op, mnem, kind, disp, a, b in three:
        for cond, ccv in (("", 1), ("dct", 2), ("dcf", 3)):
            k = "sub" if kind == "subr" else kind
            c, f = op_body(k, a, b)
            emit(L, mnem, disp, "b_op6=%#x & b_cc=%d & SX & SY & DZR & DZW" % (op, ccv), c, f, cond, W)
    # shifts by register
    for op, mnem, fn in ((0b100100, "psha", psha), (0b100000, "pshl", pshl)):
        for cond, ccv in (("", 1), ("dct", 2), ("dcf", 3)):
            amt = "(SY >> 16):1" if mnem == "pshl" else "(SY >> 16):1"
            if mnem == "psha":
                amt_lines = ["local sysh:5 = SY >> 16;", "local s7:1 = sysh:1;", "s7 = (s7 << 1) s>> 1;"]
                c, f = fn("SX", "s7")
            else:
                amt_lines = ["local sysh:5 = SY >> 16;", "local s6:1 = sysh:1;", "s6 = (s6 << 2) s>> 2;"]
                c, f = fn("SX", "s6")
            emit(L, mnem, "SX,SY,DZR", "b_op6=%#x & b_cc=%d & SX & SY & DZR & DZW" % (op, ccv),
                 amt_lines + c, f, cond, W)
    # unconditional-only three operand: PADDC, PSUBC (cc 00 of PADD/PSUB), PCMP (cc 00 of PSUB Sy,Sx)
    c, f = op_body("addc", "SX", "SY")
    emit(L, "paddc", "SX,SY,DZR", "b_op6=0b101100 & b_cc=0 & SX & SY & DZR & DZW", c, f, "", W)
    c, f = op_body("subc", "SX", "SY")
    emit(L, "psubc", "SX,SY,DZR", "b_op6=0b101000 & b_cc=0 & SX & SY & DZR & DZW", c, f, "", W)
    c, f = op_body("sub", "SX", "SY")
    emit(L, "pcmp", "SX,SY", "b_op6=0b100001 & b_cc=0 & SX & SY & b_dz=0", c, f, "", [])

    # PWAD/PWSB: named in manual table 3.15 (unconditional three-operand operations) and decoded by
    # GNU objdump at the cc = 00 slots of POR and PXOR; no manual describes what they compute
    for op, mnem in ((0b101101, "pwad"), (0b101001, "pwsb")):
        emit(L, mnem, "SX,SY,DZR", "b_op6=%#x & b_cc=0 & SX & SY & DZR & DZW" % op,
             ["local res:5 = %s(SX, SY);" % mnem], [], "", W)

    # two-operand: (op6, sub-field value selecting the form, mnemonic, kind, source side)
    # the other source field is a constant: Sx forms fix b_sy, Sy forms fix b_sx
    two = []
    for base, side in ((0b100010, "SX"), (0b101010, "SY")):
        two += [(base, side, 0, "pdec", "dec", (1, 2, 3)), (base, side, 1, "pabs", "abs", (2, 3))]
    for base, side in ((0b100110, "SX"), (0b101110, "SY")):
        two += [(base, side, 0, "pinc", "inc", (1, 2, 3)), (base, side, 1, "prnd", "rnd", (2, 3))]
    for base, side in ((0b100111, "SX"), (0b101111, "SY")):
        two += [(base, side, 0, "pdmsb", "dmsb", (1, 2, 3)), (base, side, 1, "pswap", "swap", (1, 2, 3))]
    two += [(0b110010, "SX", 0, "pneg", "neg", (1, 2, 3)), (0b111010, "SY", 0, "pneg", "neg", (1, 2, 3)),
            (0b110110, "SX", 0, "pcopy", "copy", (1, 2, 3)), (0b111110, "SY", 0, "pcopy", "copy", (1, 2, 3))]
    for op, side, fv, mnem, kind, ccs in two:
        fix = "b_sy=%d" % fv if side == "SX" else "b_sx=%d" % fv
        for ccv in ccs:
            cond = {1: "", 2: "dct", 3: "dcf"}[ccv]
            c, f = op_body(kind, side, None)
            emit(L, mnem, "%s,DZR" % side, "b_op6=%#x & b_cc=%d & %s & %s & DZR & DZW" % (op, ccv, fix, side),
                 c, f, cond, W)
    # unconditional PABS / PRND (cc 00): Table 3.17/3.24 give sub-field 00, table 6.39 also 01
    for base, mnem, kind in ((0b100010, "pabs", "abs"), (0b100110, "prnd", "rnd"),
                             (0b101010, "pabs", "abs"), (0b101110, "prnd", "rnd")):
        side = "SX" if (base & 0b001000) == 0 else "SY"
        for fv in (0, 1):
            fix = "b_sy=%d" % fv if side == "SX" else "b_sx=%d" % fv
            c, f = op_body(kind, side, None)
            emit(L, mnem, "%s,DZR" % side, "b_op6=%#x & b_cc=0 & %s & %s & DZR & DZW" % (base, fix, side),
                 c, f, "", W)
    # PCLR
    for ccv in (1, 2, 3):
        cond = {1: "", 2: "dct", 3: "dcf"}[ccv]
        c, f = op_body("clr", None, None)
        emit(L, "pclr", "DZR", "b_op6=0b100011 & b_cc=%d & b_sx=0 & b_sy=0 & DZR & DZW" % ccv, c, f, cond, W)
    # PSTS / PLDS
    for op, mnem, reg, isst in ((0b110011, "psts", "MACH", True), (0b110111, "psts", "MACL", True),
                                (0b111011, "plds", "MACH", False), (0b111111, "plds", "MACL", False)):
        for ccv in (1, 2, 3):
            cond = {1: "", 2: "dct", 3: "dcf"}[ccv]
            pat = "b_op6=%#x & b_cc=%d & b_sx=0 & b_sy=0 & DZR & DZW" % (op, ccv)
            if isst:
                emit(L, mnem, '"%s",DZR' % reg, pat, ["local res:5 = sext(%s);" % reg], [], cond, W)
            else:
                emit(L, mnem, 'DZR,"%s"' % reg, pat, ["local v:4 = DZR:4;"], [], cond, ["%s = v;" % reg])
    # shifts by immediate (unconditional only): DZ is source and destination
    c, f = psha("DZR", "PSIMM")
    emit(L, "psha", "PSIMM,DZR", "b_hi5=0b00010 & PSIMM & DZR & DZW", c, f, "", W)
    c, f = pshl("DZR", "PSIMM")
    emit(L, "pshl", "PSIMM,DZR", "b_hi5=0b00000 & PSIMM & DZR & DZW", c, f, "", W)

    # PMULS and the six-operand forms; all sources are read before any result is written
    mul = ["local p:4 = (sext(SE) * sext(SF)) << 1;",
           "local ovm:1 = (S != 0) && (SE == 0x8000) && (SF == 0x8000);",
           "p = (zext(ovm) * 0x7fffffff) | (zext(ovm == 0) * p);",
           "local gres:5 = sext(p);"]
    emit(L, "pmuls", "SE,SF,DG", "b_hi4=0b0100 & b_mid4=0 & b_du=0 & SE & SF & DG", mul, [], "", ["dg_r = gres:4;", "dgg_r = gres(4);"])
    c, f = op_body("clr", None, None)
    emit(L, "pclr", 'DU "pmuls" SE,SF,DG', "b_hi4=0b0100 & b_mid4=1 & SE & SF & DG & DU",
         mul + ["local res:5 = 0;"], f, "", ["dg_r = gres:4;", "dgg_r = gres(4);", "du_r = 0;", "dug_r = 0;"])
    for hi, mnem, kind in ((0b0111, "padd", "add"), (0b0110, "psub", "sub")):
        c, f = op_body(kind, "SX", "SY")
        emit(L, mnem, 'SX,SY,DU "pmuls" SE,SF,DG', "b_hi4=%#x & SE & SF & SX & SY & DG & DU" % hi,
             mul + c, f, "", ["dg_r = gres:4;", "dgg_r = gres(4);", "du_r = res:4;", "dug_r = res(4);"])
    print("\n".join(L))


if __name__ == "__main__":
    main()
