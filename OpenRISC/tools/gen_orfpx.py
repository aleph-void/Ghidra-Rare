#!/usr/bin/env python3
"""Generate data/languages/OpenRISC_ORFPX.sinc: ORFPX32 single precision and ORFPX64A32
double precision on 32-bit register pairs (OpenRISC 1000 architecture manual 1.4, ch. 5.4/5.5).

  gen_orfpx.py > data/languages/OpenRISC_ORFPX.sinc

A pair {rN1, rN2} holds a double with the most significant word in rN1; rN2 is rN1+1, or rN1+2
when the pair bit (10 for D, 9 for A, 8 for B) is set. Pairs that would need r32/r33 do not
exist and are not decoded (binutils prints them as r32/r33).
"""

out = []
w = out.append
w("# OpenRISC ORFPX32 / ORFPX64A32 floating point. Generated by gen_orfpx.py; do not edit.")
w("")
w("define pcodeop fp_rem;")
w("define pcodeop fp_cust1;")
w("")

# register-pair operands
for tab, field, pbit in (("dpA", "rA", "pA"), ("dpB", "rB", "pB"), ("dpD", "rD", "pD"), ("dpDv", "rD", "pD")):
    for n in range(32):
        for p in (0, 1):
            m = n + 1 + p
            if m > 31:
                continue
            pat = f"{field}={n} & {pbit}={p}"
            if tab == "dpD":
                w(f"{tab}: \"r{n},r{m}\" is {pat} {{ r{n} = fpres(4); r{m} = fpres:4; }}")
            else:
                w(f"{tab}: \"r{n},r{m}\" is {pat} {{ local v:8 = (zext(r{n}) << 32) | zext(r{m}); export v; }}")
    w("")

w("""macro fnan2(res, a, b) {
	res = nan(a) || nan(b);
}

#
# ORFPX32: single precision in general-purpose registers
#
with : opcode = 0x32 {
	:lf.add.s rD, rA, rB is f_0_10 = 0x00 & rD & rA & rB { rD = rA f+ rB; }
	:lf.sub.s rD, rA, rB is f_0_10 = 0x01 & rD & rA & rB { rD = rA f- rB; }
	:lf.mul.s rD, rA, rB is f_0_10 = 0x02 & rD & rA & rB { rD = rA f* rB; }
	:lf.div.s rD, rA, rB is f_0_10 = 0x03 & rD & rA & rB { rD = rA f/ rB; }
	:lf.itof.s rD, rA    is f_0_10 = 0x04 & f_11_15 = 0 & rD & rA { rD = int2float(rA); }
	:lf.ftoi.s rD, rA    is f_0_10 = 0x05 & f_11_15 = 0 & rD & rA { rD = trunc(rA); }
	:lf.rem.s rD, rA, rB is f_0_10 = 0x06 & rD & rA & rB { rD = fp_rem(rA, rB); }
	# binutils/gcc form: rD <- rD + rA * rB
	:lf.madd.s rD, rA, rB is f_0_10 = 0x07 & rD & rA & rB { rD = rD f+ (rA f* rB); }

	:lf.sfeq.s  rA, rB is f_0_10 = 0x08 & f_21_25 = 0 & rA & rB { F = rA f== rB; }
	:lf.sfne.s  rA, rB is f_0_10 = 0x09 & f_21_25 = 0 & rA & rB { local u; fnan2(u, rA, rB); F = !u && (rA f!= rB); }
	:lf.sfgt.s  rA, rB is f_0_10 = 0x0a & f_21_25 = 0 & rA & rB { F = rA f> rB; }
	:lf.sfge.s  rA, rB is f_0_10 = 0x0b & f_21_25 = 0 & rA & rB { F = rA f>= rB; }
	:lf.sflt.s  rA, rB is f_0_10 = 0x0c & f_21_25 = 0 & rA & rB { F = rA f< rB; }
	:lf.sfle.s  rA, rB is f_0_10 = 0x0d & f_21_25 = 0 & rA & rB { F = rA f<= rB; }
	:lf.sfueq.s rA, rB is f_0_10 = 0x28 & f_21_25 = 0 & rA & rB { local u; fnan2(u, rA, rB); F = u || (rA f== rB); }
	:lf.sfune.s rA, rB is f_0_10 = 0x29 & f_21_25 = 0 & rA & rB { local u; fnan2(u, rA, rB); F = u || (rA f!= rB); }
	:lf.sfugt.s rA, rB is f_0_10 = 0x2a & f_21_25 = 0 & rA & rB { local u; fnan2(u, rA, rB); F = u || (rA f> rB); }
	:lf.sfuge.s rA, rB is f_0_10 = 0x2b & f_21_25 = 0 & rA & rB { local u; fnan2(u, rA, rB); F = u || (rA f>= rB); }
	:lf.sfult.s rA, rB is f_0_10 = 0x2c & f_21_25 = 0 & rA & rB { local u; fnan2(u, rA, rB); F = u || (rA f< rB); }
	:lf.sfule.s rA, rB is f_0_10 = 0x2d & f_21_25 = 0 & rA & rB { local u; fnan2(u, rA, rB); F = u || (rA f<= rB); }
	:lf.sfun.s  rA, rB is f_0_10 = 0x2e & f_21_25 = 0 & rA & rB { fnan2(F, rA, rB); }

	:lf.cust1.s rA, rB is f_0_10 = 0xd0 & f_21_25 = 0 & rA & rB { fp_cust1(rA, rB); }
}

#
# ORFPX64A32: double precision in register pairs
#
with : opcode = 0x32 {
	:lf.add.d dpD, dpA, dpB is f_0_7 = 0x10 & dpD & dpA & dpB { fpres = dpA f+ dpB; build dpD; }
	:lf.sub.d dpD, dpA, dpB is f_0_7 = 0x11 & dpD & dpA & dpB { fpres = dpA f- dpB; build dpD; }
	:lf.mul.d dpD, dpA, dpB is f_0_7 = 0x12 & dpD & dpA & dpB { fpres = dpA f* dpB; build dpD; }
	:lf.div.d dpD, dpA, dpB is f_0_7 = 0x13 & dpD & dpA & dpB { fpres = dpA f/ dpB; build dpD; }
	:lf.itof.d dpD, dpA is f_0_7 = 0x14 & f_11_15 = 0 & pB = 0 & dpD & dpA { fpres = int2float(dpA); build dpD; }
	:lf.ftoi.d dpD, dpA is f_0_7 = 0x15 & f_11_15 = 0 & pB = 0 & dpD & dpA { fpres = trunc(dpA); build dpD; }
	:lf.rem.d dpD, dpA, dpB is f_0_7 = 0x16 & dpD & dpA & dpB { fpres = fp_rem(dpA, dpB); build dpD; }
	# the accumulator is the destination pair itself (dpDv reads it, dpD writes it)
	:lf.madd.d dpD, dpA, dpB is f_0_7 = 0x17 & dpD & dpDv & dpA & dpB { fpres = dpDv f+ (dpA f* dpB); build dpD; }

	:lf.sfeq.d  dpA, dpB is f_0_7 = 0x18 & f_21_25 = 0 & pD = 0 & dpA & dpB { F = dpA f== dpB; }
	:lf.sfne.d  dpA, dpB is f_0_7 = 0x19 & f_21_25 = 0 & pD = 0 & dpA & dpB { local u; fnan2(u, dpA, dpB); F = !u && (dpA f!= dpB); }
	:lf.sfgt.d  dpA, dpB is f_0_7 = 0x1a & f_21_25 = 0 & pD = 0 & dpA & dpB { F = dpA f> dpB; }
	:lf.sfge.d  dpA, dpB is f_0_7 = 0x1b & f_21_25 = 0 & pD = 0 & dpA & dpB { F = dpA f>= dpB; }
	:lf.sflt.d  dpA, dpB is f_0_7 = 0x1c & f_21_25 = 0 & pD = 0 & dpA & dpB { F = dpA f< dpB; }
	:lf.sfle.d  dpA, dpB is f_0_7 = 0x1d & f_21_25 = 0 & pD = 0 & dpA & dpB { F = dpA f<= dpB; }
	:lf.sfueq.d dpA, dpB is f_0_7 = 0x38 & f_21_25 = 0 & pD = 0 & dpA & dpB { local u; fnan2(u, dpA, dpB); F = u || (dpA f== dpB); }
	:lf.sfune.d dpA, dpB is f_0_7 = 0x39 & f_21_25 = 0 & pD = 0 & dpA & dpB { local u; fnan2(u, dpA, dpB); F = u || (dpA f!= dpB); }
	:lf.sfugt.d dpA, dpB is f_0_7 = 0x3a & f_21_25 = 0 & pD = 0 & dpA & dpB { local u; fnan2(u, dpA, dpB); F = u || (dpA f> dpB); }
	:lf.sfuge.d dpA, dpB is f_0_7 = 0x3b & f_21_25 = 0 & pD = 0 & dpA & dpB { local u; fnan2(u, dpA, dpB); F = u || (dpA f>= dpB); }
	:lf.sfult.d dpA, dpB is f_0_7 = 0x3c & f_21_25 = 0 & pD = 0 & dpA & dpB { local u; fnan2(u, dpA, dpB); F = u || (dpA f< dpB); }
	:lf.sfule.d dpA, dpB is f_0_7 = 0x3d & f_21_25 = 0 & pD = 0 & dpA & dpB { local u; fnan2(u, dpA, dpB); F = u || (dpA f<= dpB); }
	:lf.sfun.d  dpA, dpB is f_0_7 = 0x3e & f_21_25 = 0 & pD = 0 & dpA & dpB { fnan2(F, dpA, dpB); }

	# binutils prints no operands for lf.cust1.d
	:lf.cust1.d is f_0_7 = 0xe0 & f_21_25 = 0 & pD = 0 { fp_cust1(); }

	# arch manual 1.3+ conversions (not in binutils 2.45)
	:lf.stod.d dpD, rA is f_0_7 = 0x34 & f_11_15 = 0 & pA = 0 & pB = 0 & dpD & rA { fpres = float2float(rA); build dpD; }
	:lf.dtos.d rD, dpA is f_0_7 = 0x35 & f_11_15 = 0 & pD = 0 & pB = 0 & rD & dpA { rD = float2float(dpA); }
}
""")
print("\n".join(out))
